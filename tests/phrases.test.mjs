  assert.match(last(), /112/u);
  assert.match(last(), /рядом|никуда не ухожу/u);
  assert.doesNotMatch(last(), /мяу|мур|(?:^|\s)ня(?:$|[\s~!.])/iu, "к серьёзному ответу манера не добавляется");
  assert.equal(chats().length, 0, "модель не тратилась");
