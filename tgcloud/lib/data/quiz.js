/**
 * Темы, которые можно попросить: название, по каким словам узнаётся, из каких
 * разделов берутся вопросы. «Всякое» — только в общем наборе.
 */
const THEME_LIST = [
  ["география", "географ|стран|столиц|город", ["география"]],
  ["наука", "наук|физик|хими|биолог|математ|числ|цифр", ["наука", "числа"]],
  ["книги и искусство", "книг|литератур|писател|искусств|живопис|культур", ["культура"]],
  ["история", "истори", ["история"]],
  ["аниме", "аниме|манг", ["аниме"]],
  ["кино", "кино|фильм|мульт", ["кино"]],
  ["игры", "^(?:(?:видео|компьютерн\\S+\\s+)?игр(?:ы|ам|ах)?|игров\\S*)$|видеоигр|гейм", ["игры"]],
  ["музыка", "музык|песн|композитор", ["музыка"]],
  ["космос", "космос|космич|планет|звезд|астроном", ["космос"]],
  ["животные", "животн|звер|природ|птиц", ["животные"]],
];
const OFFSETS = (() => { const map = {}; let at = 0; for (const [name, rows] of Object.entries(SECTIONS)) { map[name] = [at, at + rows.length]; at += rows.length; } return map; })();
export const QUIZ_THEMES = Object.freeze(THEME_LIST.map(([title, words, sections]) => Object.freeze({
  title, pattern: new RegExp(words, "u"),
  indices: Object.freeze(sections.flatMap(name => Array.from({ length: OFFSETS[name][1] - OFFSETS[name][0] }, (_, index) => OFFSETS[name][0] + index))),
})));

/** «про аниме», «по кино» → тема, или null: такой темы нет. */
export function quizTheme(text) {
  const value = String(text ?? "").toLowerCase().replace(/ё/gu, "е");
  return QUIZ_THEMES.find(theme => theme.pattern.test(value)) ?? null;
}
