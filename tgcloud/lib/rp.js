/**
 * Как Аи отвечает, когда действие обращено к ней.
 * `adult: false` — человек сам сказал, что ему нет восемнадцати.
 * Возвращает `{ text, gif, emoji, mood, deed }`; `deed` — что это меняет в
 * отношениях («caress», «shove») или null.
 */
export function reactionFor(action, { score = 0, owner = false, formal = true, adult = null, random = Math.random, phrase = null } = {}) {
  const level = levelOf(score, { owner });
  const friendly = action.kind === "romantic" && adult === false;
  const [lines, gif, emoji, mood] = friendly ? FRIENDLY : REACTIONS[action.kind][level];
  // Слова — из словаря: сначала запас самого действия, потом запас вида.
  const own = !friendly && typeof phrase === "function" ? phrase(action, level) : null;
  if (own) return { text: own, gif, emoji, mood, deed: deedOf(action, level, owner), level };
  const line = lines[Math.min(lines.length - 1, Math.floor(random() * lines.length))];
  const near = level === "warm" || level === "close";
  const deed = friendly || owner ? null
    : (action.kind === "kind" || action.kind === "romantic") && near ? "caress"
    : action.kind === "rough" && !near ? "shove" : null;
  // С хозяином и чужими — на «вы»; «ты» приходит с близостью.
  return { text: speak(line, owner ? true : formal), gif, emoji, mood, deed, level };
}

/** Действия, для которых нужна близость: без неё она не трогает и не даёт трогать себя. */
const TOUCHY = new Set(["hug", "cuddle", "pat", "carry", "tuck", "blanket"]);
const BOLD = new Set(["kiss", "flirt", "kabedon"]);
const RANK = Object.freeze({ cold: 0, first: 1, warm: 2, close: 3, owner: 4 });

/**
 * Сделает ли Аи действие сама, когда её просят: «поцелуй меня», «пни его».
 *   level  — насколько ей близок тот, с кем это делается;
 *   asker  — насколько близок тот, кто просит (для третьих лиц);
 *   order  — просит хозяин: его слово она выполняет.
 * Возвращает `{ ok: true, note }` или `{ ok: false, text, gif }`.
 */
export function willingness(action, { level = "first", asker = level, order = false, adult = null, flirt = true, third = false, formal = true } = {}) {
  const say = (text, gif) => ({ ok: false, text: speak(text, formal), gif });
  if (action.kind === "romantic" && (adult === false || flirt === false)) return say("Это — нет. {Давай|Давайте} по-дружески.", "nope");
  if (order) return { ok: true, note: third && (action.kind === "romantic" || action.kind === "rough") ? "Раз хозяин велел." : "" };
  if (RANK[asker] === 0) return say("Не {командуй|командуйте} мной.", "nope");
  const rank = RANK[level];
  if (action.kind === "rough") return { ok: true, note: third ? "" : "Желание исполнено." };
  if (action.kind === "romantic") {
    const need = BOLD.has(action.key) ? 3 : 2;
    if (rank >= need) return { ok: true, note: "" };
    if (third) return say("Так я поступаю только с теми, кто мне близок.", "nope");
    return rank <= 1 ? say("Мы едва знакомы. Нет.", "shocked") : say("Рано. Но просьбу я запомнила.", "blush");
  }
  const need = TOUCHY.has(action.key) || action.kind === "odd" ? 2 : 1;
  if (rank >= need) return { ok: true, note: "" };
  return third ? say("С незнакомыми я так не делаю.", "nope") : say("Мы пока не настолько близки.", "nope");
}

