/**
 * Имя в винительном падеже: «обнимает Машу», «пинает Ивана». Склоняется только
 * то, в чём нельзя ошибиться: одно слово кириллицей на -а/-я и известные
 * мужские имена. Ник остаётся как есть — «обнимает DarkLord».
 */
export function accusative(name) {
  const value = String(name ?? "").trim();
  if (!/^[А-ЯЁа-яё]{3,}$/u.test(value)) return value;
  const key = value.toLowerCase().replace(/ё/gu, "е");
  if (ODD_ACCUSATIVE[key]) return ODD_ACCUSATIVE[key];
  const last = value.slice(-1), stem = value.slice(0, -1);
  if (last === "а") return `${stem}у`;
  if (last === "я") return `${stem}ю`;
  if (!MALE.has(key)) return value;
  if (last === "й" || last === "ь") return `${stem}я`;
  return `${value}а`;
}

const ODD_DATIVE = Object.freeze({ павел: "Павлу", лев: "Льву", петр: "Петру" });
/** Имя в дательном падеже: «машет Маше», «дарит Ивану». Те же осторожные правила. */
export function dative(name) {
  const value = String(name ?? "").trim();
  if (!/^[А-ЯЁа-яё]{3,}$/u.test(value)) return value;
  const key = value.toLowerCase().replace(/ё/gu, "е");
  if (ODD_DATIVE[key]) return ODD_DATIVE[key];
  const last = value.slice(-1), stem = value.slice(0, -1);
  if (value.endsWith("ия")) return `${stem}и`;
  if (last === "а" || last === "я") return `${stem}е`;
  if (!MALE.has(key)) return value;
  if (last === "й" || last === "ь") return `${stem}ю`;
  return `${value}у`;
}

/** Строка о действии одного человека над другим. `a`, `b` — уже готовые подписи. */
export function lineFor(action, a, b, { tail = "", bName = "" } = {}) {
  const rest = tail || action.tail;
  if (action.key === "highfive") return `${action.emoji} ${a} и ${b} дают друг другу пять${rest ? ` ${rest}` : ""}`;
  if (action.key === "handshake") return `${action.emoji} ${a} и ${b} жмут друг другу руки${rest ? ` ${rest}` : ""}`;
  // Подпись может быть ссылкой: склоняется имя внутри неё.
  const bent = bName ? (action.how === "dat" ? dative(bName) : accusative(bName)) : "";
  const object = bent && bent !== bName ? b.replace(bName, bent) : b;
  return `${action.emoji} ${a} ${action.verb} ${object}${rest ? ` ${rest}` : ""}`;
}

/** Действие над собой: без рода и без обиды. */
export function selfLine(action, a) {
  return `${action.emoji} ${a} пробует это на себе. Зрелище на любителя.`;
}

