const speak = (text, formal) => text.replace(/\{([^|{}]*)\|([^|{}]*)\}/gu, (_, familiar, polite) => (formal ? polite : familiar));

/** Что действие меняет в отношениях: ласка от близкого — шаг навстречу, грубость от чужого — шаг назад. */
function deedOf(action, level, owner) {
  const near = level === "warm" || level === "close";
  if (owner) return null;
  return (action.kind === "kind" || action.kind === "romantic") && near ? "caress" : action.kind === "rough" && !near ? "shove" : null;
}
