/** «танцевать», «*зеваю*» → эмоция; обычная речь — null. */
export function parseEmote(text) {
  const raw = fold(text).replace(/[!.…]+$/u, "").trim();
  if (!raw || raw.length > 40) return null;
  const starred = /^\*[^*]+\*$/u.test(raw) || /^_[^_]+_$/u.test(raw);
  const value = raw.replace(/^[*_]+|[*_]+$/gu, "").replace(/\s+/gu, " ").trim();
  for (const emote of EMOTES) if ((starred ? emote.starred : emote.plain).test(value)) return emote;
  return null;
}
