export const ACTIONS = Object.freeze(TABLE.map(([key, emoji, verb, gif, kind, title, forms, order, tail = "", how = "acc"]) => Object.freeze({
  key, emoji, verb, gif, kind, title, tail, how,
  said: new RegExp(`^(?:${forms})(?=$|\\s)`, "u"),
  asked: order ? new RegExp(`^(?:${order})(?=$|\\s)`, "u") : null,
})));

/** С этих слов хвост не начинается: «убил бы», «обнять не могу», «похвалить надо» — речь, а не действие. */
const NOT_A_TAIL = /^(?:бы|б|не|ни|ли|же|что|чтобы|как|если|когда|хотя|а|но|или|ведь|только|уже|еще|тоже|то|так|там|тут|это|этот|эту|мне|меня|нас|себя|себе|надо|нужно|можно|нельзя|хочу|хочется|хотел|хотела|стоит|пора|было|будет|буду|могу|может|мог|могла|рекорд|время|тревогу)(?=$|\s)/u;
/** «Его», «тебя», «её»: это и есть адресат, а не подробность. */
const PRONOUN = /^(?:его|ее|их|тебя|вас|этого|эту|этих|ему|ей|им|тебе|вам|нему|ней|ним|ними|тобой|вами)(?=$|\s)/u;
const MENTION = /(?:^|\s)@([a-z0-9_]{3,32})(?=$|[\s,.!?])/giu;

/**
 * Разобрать фразу как действие.
 *   asked — повелительное («обними»): так просят саму Аи сделать это;
 *   toMe  — «…меня»: сделать это с тем, кто просит.
 * Возвращает `{ action, tail, mention, asked, toMe }` или null.
 */
export function parseAction(text) {
  const raw = fold(text).replace(/^[*_~\s]+|[*_~\s]+$/gu, "").replace(/[!.…?)]+$/u, "").trim();
  // Запятая посреди фразы — признак речи: «ударил по больному, да».
  if (!raw || raw.length > 80 || /[,;:]/u.test(raw)) return null;
  const mentions = [];
  let value = raw.replace(MENTION, (_, name) => { mentions.push(name.toLowerCase()); return " "; });
  // Смайлики и прочие значки — не слова действия.
  value = value.replace(/[^\p{L}\p{N}\s\-]/gu, " ").replace(/\s+/gu, " ").trim();
  if (!value) return null;
  for (const action of ACTIONS) {
    const said = value.match(action.said);
    const asked = said ? null : action.asked ? value.match(action.asked) : null;
    const hit = said ?? asked;
    if (!hit) continue;
    let tail = value.slice(hit[0].length).trim();
    let toMe = false;
    if (asked && /^(?:меня|нас|мне|нам|мной|нами)(?=$|\s)/u.test(tail)) { toMe = true; tail = tail.replace(/^(?:меня|нас|мне|нам|мной|нами)\s*/u, ""); }
    tail = tail.replace(PRONOUN, "").trim();
    if (tail.length > 40 || tail.split(" ").filter(Boolean).length > 4 || NOT_A_TAIL.test(tail)) return null;
    return { action, tail, mention: mentions[0] ?? null, asked: Boolean(asked), toMe };
  }
  return null;
}

