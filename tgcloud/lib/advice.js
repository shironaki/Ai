/**
 * Совет «что посмотреть / почитать / во что поиграть / что послушать» — из
 * источника, а не из головы (слово владельца 15.11.2026: «по возможности брала
 * из интернета»). Фильмы, сериалы, книги и игры — из Википедии: статьи с
 * карточкой нужного вида, от самых известных; «похожее на …» — поиском похожих
 * статей. Музыка — из чарта Deezer. Аниме советует `media.js` (Shikimori).
 *
 * Здесь только разбор слов. Источник молчит — отвечает словарь, как раньше.
 */
const fold = (text) => String(text ?? "").toLowerCase().replace(/ё/gu, "е").replace(/\s+/gu, " ").trim();

