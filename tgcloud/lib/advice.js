/** Хвост просьбы безобиден: в нём только «когда, с кем, какое» и слова жанра. */
function harmless(rest) {
  return String(rest ?? "").split(" ").filter(Boolean).every(word => FILLER.has(word) || GENRE_TOKEN.test(word));
}

