/**
 * Слова → просьба о совете, иначе null:
 *   { shelf }                 — «что посмотреть», «посоветуй книгу», «что послушать»;
 *   { shelf, genre }          — «посоветуй комедию», «что посмотреть из ужасов» (genre — запись из GENRES);
 *   { shelf, like }           — «фильм как Интерстеллар», «что почитать похожее на Дюну».
 * Аниме сюда не попадает (его советует каталог аниме), «что посмотреть в Казани» — тоже.
 */
export function parseAdvice(text) {
  const raw = String(text ?? "").replace(/\s+/gu, " ").trim();
  if (!raw || raw.length > 140) return null;
  const value = fold(raw).replace(/[?!.…]+$/u, "").replace(/[,«»"“”]/gu, " ").replace(/\s+/gu, " ").trim();
  if (!value || /аниме|анимешк|манг[уаи]|ранобэ|тайтл/u.test(value)) return null;

  // «Похожее на …»: полка названа словом или глаголом.
  for (const [shelf, noun] of Object.entries(NOUNS)) {
    if (shelf === "music") continue;
    const found = value.match(new RegExp(`^(?:${ASK}\\s+)?${ME}(?:(?:какой-нибудь|какую-нибудь|что-нибудь|что-то)\\s+)?(?:${noun})\\s+${LIKE}\\s+(.{2,60})$`, "u"))
      ?? value.match(new RegExp(`^(?:${ASK}\\s+)?${ME}${WHAT}\\s+${LIKE}\\s+(?:${noun})\\s+(.{2,60})$`, "u"));
    if (found) return { shelf, like: likeOf(raw, found[1]) };
  }
  const verbs = [["film", "посмотреть|глянуть"], ["book", "почитать|прочитать"], ["game", "поиграть|сыграть"]];
  for (const [shelf, verb] of verbs) {
    const found = value.match(new RegExp(`^(?:${ASK}\\s+)?${ME}(?:во\\s+)?${WHAT}\\s+(?:бы\\s+)?${ME}(?:${verb})\\s+${LIKE}\\s+(.{2,60})$`, "u"))
      ?? value.match(new RegExp(`^(?:${ASK}\\s+)?${ME}(?:во\\s+)?${WHAT}\\s+${LIKE}\\s+(.{2,60}?)\\s+(?:${verb})$`, "u"));
    if (found) return { shelf, like: likeOf(raw, found[1]) };
  }

  for (const [name, frame, restAt = 1] of FRAMES) {
    const found = value.match(frame);
    if (!found) continue;
    const before = restAt === 2 ? found[1] ?? "" : "";
    const rest = found[restAt] ?? "";
    if (!harmless(before) || !harmless(rest)) continue;
    let shelf = name;
    const all = `${before} ${rest}`;
    // «Что посмотреть из сериалов», «посоветуй детектив почитать» — полку называет хвост.
    if (shelf === "film" && /сериал/u.test(all)) shelf = "series";
    if (shelf === "film" && /почитать|прочитать|книг/u.test(all)) shelf = "book";
    if (shelf === "film" && /поиграть|сыграть/u.test(all)) shelf = "game";
    // Жанр — из всей фразы: он бывает и самим существительным («комедию»), и прилагательным, и «из ужасов».
    const genre = shelf === "music" ? null : genreOf(value.replace(/посмотреть|посоветуй/gu, " "));
    if (shelf === "music" && /\S/u.test(all.replace(/\s+/gu, " ").trim()) && !harmless(all)) continue;
    return { shelf, ...(genre ? { genre } : {}) };
  }
  return null;
}

/** Название из исходной фразы — с тем регистром, что написал человек. */
function likeOf(raw, folded) {
  const clean = raw.replace(/[?!.…]+$/u, "").replace(/[«»"“”]/gu, " ").replace(/\s+/gu, " ").trim();
  const at = fold(clean).lastIndexOf(folded);
  return (at >= 0 ? clean.slice(at, at + folded.length) : folded).trim();
}

/** «Гладиатор (фильм, 2000)» → { name: «Гладиатор», note: «фильм, 2000» }. */
export function titleParts(title) {
  const found = String(title ?? "").match(/^(.*?)\s*\(([^()]+)\)\s*$/u);
  return found ? { name: found[1].trim(), note: found[2].trim() } : { name: String(title ?? "").trim(), note: "" };
}
