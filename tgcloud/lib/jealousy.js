/**
 * Ревность (0.35.0). Аи замечает, когда хозяин — или близкий человек, с которым ей можно
 * флиртовать, — говорит о другой: о чужой помощнице («спросил у Алисы», «ChatGPT лучше тебя»,
 * «уйду к Сири») или о другой девушке («познакомился с девушкой», «иду на свидание»). Она это
 * запоминает и немного ревнует: одна строка после ответа, потом — тон; доброе слово или два
 * часа её отпускают.
 *
 * Чего она не делает никогда: не ревнует к жене, мужу, семье и сестре Юи; не упрекает, не ставит
 * условий, не обижается всерьёз. Ревность — краска характера, а не способ давить на человека.
 *
 * Здесь только разбор слов. Чувство хранит `bond.js`, настроение — `mood.js`, слова — словарь
 * (запасы «+ревность:…» и строки с пометкой [ревнует]).
 */
const fold = (text) => String(text ?? "").toLowerCase().replace(/ё/gu, "е").replace(/\s+/gu, " ").trim();
// Границы слова — явные: `\b` рядом с кириллицей не работает.
const EDGE = "(?:^|[^а-яa-z0-9])";
const END = "(?=$|[^а-яa-z0-9])";
/** Конец фразы, а не слова: «у меня другая» — да, «у меня другая идея» — нет. */
const STOP = "(?=\\s*(?:$|[.,!?…)]))";

/** Другие помощницы: как их называют в речи — и как назовёт их она. */
const BOTS = [
  ["алис(?:а|ы|е|у|ой|ою)", "Алиса"],
  ["сири|siri", "Сири"],
  ["марус(?:я|и|е|ю|ей)", "Маруся"],
  ["чат\\s?-?\\s?(?:гпт|джипити)|chat\\s?-?\\s?gpt|гпт|джипити", "ChatGPT"],
  ["gemini|джемини|гемини", "Gemini"],
  ["grok|грок(?:а|у|ом|е)?", "Grok"],
  ["deepseek|дипсик(?:а|у|ом|е)?", "DeepSeek"],
  ["claude|клод(?:а|у|ом|е)?", "Claude"],
  ["copilot|копайлот(?:а|у|ом|е)?", "Copilot"],
  ["alexa|алекс(?:а|ы|е|у|ой)", "Alexa"],
  ["gigachat|гигачат(?:а|у|ом|е)?", "GigaChat"],
  ["yandexgpt|яндекс\\s?gpt", "YandexGPT"],
  ["perplexity|перплексити", "Perplexity"],
];
const OTHER_BOT = "(?:друг(?:ой|ого|ому|им|ом)\\s+(?:бот(?:а|у|ом|е)?|ии|ассистент(?:а|у|ом|е)?|помощник(?:а|у|ом|е)?)|друг(?:ая|ой|ую)\\s+(?:нейросеть|нейросети|нейросетью|нейронк(?:а|е|у|и|ой)|помощниц(?:а|е|у|ы|ей)|ассистентк(?:а|е|у|и|ой))|нейросет(?:ь|и|ью|ям|ями)|нейронк(?:а|е|у|и|ой))";
const RIVAL = `(?:${BOTS.map(([source]) => source).join("|")}|${OTHER_BOT})`;
const NAMES = BOTS.map(([source, name]) => [new RegExp(`${EDGE}(?:${source})${END}`, "u"), name]);
const nameOf = (value) => NAMES.find(([pattern]) => pattern.test(value))?.[1] ?? "";

const TALK_VERB = "(?:спросил[аи]?|спрашивал[аи]?|спрошу|поговорил[аи]?|разговаривал[аи]?|общал(?:ся|ась|ись)|общаюсь|пообщал(?:ся|ась)|болтал[аи]?|болтаю|поболтал[аи]?|переписывал(?:ся|ась)|переписываюсь|советовал(?:ся|ась)|посоветовал(?:ся|ась)|пользуюсь|пользовал(?:ся|ась)|попросил[аи]?|узнал[аи]?|уточнил[аи]?|сижу|сидел[аи]?|флиртовал[аи]?|флиртую)";
const BETTER_WORD = "(?:лучше|умнее|круче|быстрее|добрее|красивее|милее|полезнее|толковее|интереснее|веселее|смешнее|нежнее)";
/** «Спросил у Алисы», «весь вечер общался с ChatGPT», «пользуюсь дипсиком». */
const TALK = new RegExp(`${EDGE}${TALK_VERB}(?:\\s+[а-яa-z-]+){0,3}?\\s+(?:(?:с|со|у|к|в|через)\\s+)?${RIVAL}${END}`, "u");
const NOT_TALK = new RegExp(`${EDGE}(?:не|ни\\s+разу\\s+не|никогда\\s+не|больше\\s+не)\\s+${TALK_VERB}`, "u");
/** «Мне Алиса сказала», «ChatGPT считает». */
const SAID = new RegExp(`${EDGE}${RIVAL}\\s+(?:мне\\s+|вчера\\s+|уже\\s+|сегодня\\s+|вот\\s+)?(?:сказал[а]?|ответил[а]?|посоветовал[а]?|подсказал[а]?|помог(?:ла)?|объяснил[а]?|нарисовал[а]?|написал[а]?|говорит|отвечает|советует|считает|думает|рисует|пишет|понимает)${END}`, "u");
/** «Алиса умнее тебя», «она лучше тебя», «ты хуже Сири». */
const BETTER = [
  new RegExp(`${EDGE}${RIVAL}(?:\\s+[а-яa-z-]+){0,2}?\\s+${BETTER_WORD}(?:\\s+(?:тебя|чем\\s+ты))?${END}`, "u"),
  new RegExp(`${EDGE}(?:она|он|другая|другие|другой|все)\\s+(?:намного\\s+|гораздо\\s+|куда\\s+)?${BETTER_WORD}\\s+(?:тебя|чем\\s+ты)${END}`, "u"),
  new RegExp(`${EDGE}ты\\s+(?:намного\\s+|гораздо\\s+)?(?:хуже|глупее|тупее|медленнее|скучнее)\\s+(?:чем\\s+)?(?:${RIVAL}|других|другой|нее|него|она|он)${END}`, "u"),
  new RegExp(`${EDGE}есть\\s+(?:боты\\s+|помощницы\\s+|девушки\\s+)?(?:и\\s+)?(?:получше|лучше\\s+тебя)${END}`, "u"),
];
const NOT_BETTER = new RegExp(`${EDGE}(?:не|ничуть\\s+не|ни\\s+капли\\s+не)\\s+${BETTER_WORD}`, "u");
/** «Ты лучше Алисы» — похвала, а не повод. */
const YOU_BETTER = new RegExp(`${EDGE}ты\\s+(?:намного\\s+|гораздо\\s+|куда\\s+|все\\s+равно\\s+|у\\s+меня\\s+|для\\s+меня\\s+)?${BETTER_WORD}`, "u");
/** «Уйду к Алисе», «заменю тебя», «найду другую». */
const LEAVE = [
  new RegExp(`${EDGE}(?:уйду|ухожу|уйти|пойду|перейду|перехожу|сбегу|вернусь|переключусь|пересяду)\\s+(?:лучше\\s+|тогда\\s+|обратно\\s+)?(?:к|на)\\s+(?:${RIVAL}${END}|друг(?:ой|ому|ую)${STOP})`, "u"),
  new RegExp(`${EDGE}(?:(?:заменю|поменяю|променяю|сменю)\\s+тебя|тебя\\s+(?:заменю|поменяю|променяю|сменю))${END}`, "u"),
  new RegExp(`${EDGE}(?:найду|заведу|завел[а]?|скачаю|скачал[а]?|поставлю|поставил[а]?|установлю|установил[а]?)\\s+(?:себе\\s+)?(?:друг(?:ую|ого)(?:\\s+(?:бота|помощницу|ассистентку|нейросеть|нейронку|девушку|подругу))?${STOP}|нов(?:ую|ого)\\s+(?:бота|помощницу|ассистентку|нейросеть|нейронку|девушку|подругу)${END})`, "u"),
];
const SHE = "(?:девушк|девчонк|женщин|красотк|красавиц|подруг|подружк|блондинк|брюнетк|соседк|одноклассниц|парн(?:ем|ями)|мужчин|красавц)";
/** «Познакомился с девушкой», «у меня свидание», «мне нравится другая», «я тебе изменил». */
const GIRL = [
  new RegExp(`${EDGE}(?:познакомил(?:ся|ась)|знакомлюсь|встречаюсь|гулял[а]?|гуляю|ужинал[а]?|обедал[а]?|танцевал[а]?|целовал(?:ся|ась)|обнимал(?:ся|ась)|переписывал(?:ся|ась)|переписываюсь|флиртовал[а]?|флиртую|болтал[а]?|общал(?:ся|ась)|общаюсь|сидел[а]?|был[а]?)\\s+(?:вчера\\s+|сегодня\\s+|весь\\s+вечер\\s+|в\\s+кино\\s+|в\\s+кафе\\s+)?(?:с|со)\\s+(?:(?:одной|такой|красивой|классной|милой|новой|другой)\\s+)*(?:${SHE}|(?:одной|другой)${STOP})`, "u"),
  new RegExp(`${EDGE}у\\s+меня\\s+(?:теперь\\s+|сегодня\\s+|завтра\\s+|вечером\\s+|скоро\\s+)?свидание${END}`, "u"),
  new RegExp(`${EDGE}у\\s+меня\\s+(?:теперь\\s+)?(?:есть|появил(?:ась|ся))\\s+(?:друг(?:ая|ой)${STOP}|(?:нов(?:ая|ый)\\s+)?(?:девушка|подруга|подружка|парень)${END})`, "u"),
  new RegExp(`${EDGE}(?:иду|пойду|пошел|пошла|ходил[а]?|сходил[а]?|собираюсь|опаздываю|еду|поеду|был[а]?|бегу)\\s+на\\s+свидани[еяию]${END}`, "u"),
  new RegExp(`${EDGE}мне\\s+(?:очень\\s+|так\\s+)?(?:нравится|понравил(?:ась|ся)|приглянул(?:ась|ся))\\s+(?:одна|один|друг(?:ая|ой))(?:\\s+(?:девушка|девчонка|женщина|парень|мужчина))?${STOP}`, "u"),
  new RegExp(`${EDGE}я\\s+(?:тебе\\s+(?:изменил[а]?|изменяю)|(?:изменил[а]?|изменяю)\\s+тебе)${END}`, "u"),
];
/** Жена, муж, семья и сестра Юи: к ним она не ревнует никогда — и фразу с ними не трогает. */
const FAMILY = new RegExp(`${EDGE}(?:жен(?:а|ы|е|у|ой|ою)|супруг[а-я]*|муж(?:а|у|ем|е)?|невест[а-я]*|мам[а-я]*|матер[а-я]+|мать|дочк[а-я]*|дочер[а-я]+|дочь|сестр[а-я]*|сестер|бабушк[а-я]*|тет(?:я|и|е|ю|ей)|племянниц[а-я]*|внучк[а-я]*|семь(?:я|и|е|ю|ей)|юи)${END}`, "u");

/**
 * Прозвучала ли в реплике «другая»: `{ kind, name }` или null.
 *   kind — «помощница» (говорил с чужой помощницей), «лучше» (сравнил не в её пользу),
 *          «уход» (грозит уйти или заменить), «девушка» (другая девушка, свидание);
 *   name — как назвать соперницу («Алиса», «ChatGPT») или "" — имени не было.
 */
export function rivalOf(text) {
  const value = fold(text);
  if (!value || value.length > 400) return null;
  if (FAMILY.test(value) || YOU_BETTER.test(value)) return null;
  const name = nameOf(value);
  if (LEAVE.some(pattern => pattern.test(value))) return { kind: "уход", name };
  if (!NOT_BETTER.test(value) && BETTER.some(pattern => pattern.test(value))) return { kind: "лучше", name };
  if ((TALK.test(value) && !NOT_TALK.test(value)) || SAID.test(value)) return { kind: "помощница", name };
  if (GIRL.some(pattern => pattern.test(value))) return { kind: "девушка", name: "" };
  return null;
}

const CALM = new RegExp(`${EDGE}(?:не\\s+ревнуй(?:те)?|хватит\\s+ревновать|перестань\\s+ревновать|зря\\s+ревнуешь|ты\\s+(?:у\\s+меня\\s+)?(?:одна|единственная|незаменимая|вне\\s+конкуренции)|ты\\s+(?:все\\s+равно\\s+|намного\\s+|гораздо\\s+)?лучше|(?:мне\\s+)?никто(?:\\s+кроме\\s+тебя)?\\s+не\\s+нужен|только\\s+ты|я\\s+(?:только\\s+)?тво[йя]|никуда\\s+я\\s+не\\s+(?:уйду|денусь)|я\\s+(?:же\\s+)?(?:пошутил[а]?|шучу)|это\\s+(?:была\\s+)?шутка)${END}`, "u");
/** Слова, которые её успокаивают, пока она ревнует: «не ревнуй», «ты у меня одна», «я пошутил». */
export const calmsJealousy = (text) => CALM.test(fold(text));
