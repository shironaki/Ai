/** Прилагательное при названии («зелёный чай», «белые розы») и связки. Строка уже приведена: «ё» → «е». */
const ADJECTIVE = /^[а-я]{2,}(?:ый|ий|ой|ая|яя|ое|ее|ые|ие|ую|юю)$/u;
const CONNECTOR = /^(?:и|с|со|или|почти|очень|ярко|бледно|нежно|конечно|наверное|пожалуй)$/u;

/**
 * «Значение узнано целиком»: каждое слово — название из списка, прилагательное
 * при нём или связка, и хотя бы одно — из списка. «Зелёный чай» — напиток;
 * «чай остыл», «уважаю» и «расскажи про чай» — нет. `strip` снимает узнанные
 * слова и возвращает остаток строки; null — ничего не узнано.
 */
const recognised = (strip) => (value) => {
  const text = fold(value).replace(/[.,!?«»"„“”'()]+/gu, " ").replace(/\s+/gu, " ").trim();
  if (!text) return false;
  const rest = strip(text);
  if (rest == null) return false;
  return rest.replace(/-/gu, " ").split(" ").filter(Boolean).every(token => ADJECTIVE.test(token) || CONNECTOR.test(token));
};
/** Список начал слов. `\b` рядом с кириллицей не работает; узнанное слово снимается до конца. */
const stems = (list) => {
  const pattern = new RegExp(`(?<![а-яa-z0-9])(?:${list})[а-я]*`, "gu");
  return recognised((text) => { const rest = text.replace(pattern, " "); return rest === text ? null : rest.replace(/\s+/gu, " ").trim(); });
};
const ANIMAL_STEMS = ANIMALS.flatMap(row => String(row[3] ?? row[1] ?? "").split(" ")).filter(word => word.length >= 3).map(word => (word.length > 4 ? word.slice(0, -1) : word));
/** Окончание после начала слова: «кот» + «ики», но не «кот» + «лета» и не «кит» + «ай». */
