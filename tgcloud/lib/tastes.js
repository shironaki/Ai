/** Значение — одна короткая строка, как сказал человек; без точки в конце. */
export function cleanTaste(value) {
  let text = String(value ?? "").replace(/\s+/gu, " ").trim().replace(/[.!…]+$/u, "").trim();
  // Кавычки снимаются, только когда в них всё значение: «Пицца «Маргарита»» остаётся как есть.
  const inner = text.match(/^[«"„“']([^«»"„“”']+)[»"”“']$/u);
  if (inner) text = inner[1].trim();
  if (!text || text.length > MAX_VALUE || /[\n<>]/u.test(text) || /https?:|t\.me\//iu.test(text)) return "";
  return text;
}

/**
 * Что человек хочет от анкеты:
 *   { set: kind, value }   — «мой любимый цвет — синий»;
 *   { get: kind }          — «какой мой любимый цвет?»;
 *   { list: true }         — «что я люблю?», «моя анкета»;
 *   { start: true }        — «анкета», «спроси меня о любимом»;
 *   { drop: kind }         — «забудь мой любимый цвет»;
 *   { clear: true }        — «забудь анкету».
 * Не про анкету — null. Слова о ней самой («твой любимый цвет») сюда не попадают.
 */
export function parseTaste(text) {
  const raw = String(text ?? "").replace(/\s+/gu, " ").trim();
  if (!raw || raw.length > 140) return null;
  const value = fold(raw).replace(/^(?:а|и|ну|кстати)[\s,]+/u, "").replace(/^запомни(?:те)?[\s,:—-]+(?:что\s+)?/u, "");
  const bare = value.replace(/[.!?…]+$/u, "").trim();

  if (/^(?:(?:давай|начн[её]м|продолжим|заполним|устрой|проведи)\s+)?анкет[ауы]?(?:\s+(?:любим(?:ого|ое|ых)|про\s+любимое|о\s+любимом))?$|^спроси(?:те)?\s+(?:меня\s+)?(?:о|про|об)\s+(?:мо(?:ем|их)\s+)?(?:любим(?:ом|ое|ых)|вкус(?:ах|ы))$|^спроси(?:те)?\s+(?:меня\s+)?,?\s*что\s+я\s+люблю$|^узнай\s+меня\s+(?:получше|поближе|лучше)$/u.test(bare)) return { start: true };
  if (/^(?:забудь|сотри|очисти|удали)(?:те)?\s+(?:мою\s+|всю\s+)?анкету$|^забудь(?:те)?\s+(?:вс[её]\s+)?(?:,\s*)?что\s+я\s+люблю$/u.test(bare)) return { clear: true };
  if (/^(?:что|чего)\s+я\s+люблю$|^(?:покажи\s+)?мо[яю]\s+анкет[ау]$|^мо[еи]\s+любим(?:ое|ые)$|^что\s+ты\s+(?:знаешь|помнишь)\s+(?:о|про)\s+мо(?:их|и)\s+(?:вкус(?:ах|ы)|любим(?:ых|ые|ом|ое))$|^что\s+я\s+(?:тебе\s+)?(?:рассказывал[а]?|говорил[а]?)\s+(?:о|про)\s+любим(?:ом|ое)$|^что\s+мне\s+нравится$/u.test(bare)) return { list: true };

  let match = bare.match(new RegExp(`^(?:забудь|сотри|удали)(?:те)?\\s+(?:мо[йюеи]\\s+)?(?:${ADJ}|любим(?:ую|ого))\\s+(${NOUN})$`, "u"));
  if (match) { const kind = kindOf(match[1]); return kind ? { drop: kind.key } : null; }

  // Вопрос о своём: без «мой» или «у меня» это вопрос о ней, и отвечает словарь.
  match = bare.match(new RegExp(`^(?:как(?:ой|ая|ое|ие)|что\\s+за)\\s+(?:у\\s+меня\\s+|мо[йяеи]\\s+)(?:${ADJ}\\s+)(${NOUN})$`, "u"))
    ?? bare.match(new RegExp(`^(?:как(?:ой|ая|ое|ие)\\s+)?${ADJ}\\s+(${NOUN})\\s+у\\s+меня$`, "u"))
    ?? bare.match(new RegExp(`^мо[йяеи]\\s+${ADJ}\\s+(${NOUN})\\s+как(?:ой|ая|ое|ие)$`, "u"))
    ?? bare.match(new RegExp(`^(?:ты\\s+)?(?:помнишь|знаешь)\\s*,?\\s*(?:как(?:ой|ая|ое|ие)\\s+)?(?:у\\s+меня\\s+|мо[йяеи]\\s+)${ADJ}\\s+(${NOUN})$`, "u"));
  if (match) { const kind = kindOf(match[1]); return kind ? { get: kind.key } : null; }

  // Рассказ: значение берётся из исходной строки — с заглавными, как сказал человек.
  const told = new RegExp(`^(?:мо[йяеи]\\s+${ADJ}|${ADJ}\\s+у\\s+меня|у\\s+меня\\s+${ADJ})\\s+(${NOUN})(${DASH})(.+)$`, "u");
  const told2 = new RegExp(`^${ADJ}\\s+(${NOUN})\\s+у\\s+меня(${DASH})(.+)$`, "u");
  match = bare.match(told2) ?? bare.match(told);
  if (match) {
    const kind = kindOf(match[1].trim());
    if (!kind) return null;
    const tail = match[3].trim();
    if (!tail || /^(?:как(?:ой|ая|ое|ие)|что|кто)(?:\s|$)/u.test(tail) || value.endsWith("?")) return null;
    // Хвост исходной строки той же длины: регистр и «ё» — как у человека.
    const said = raw.replace(/[.!…]+$/u, "").trim().slice(-tail.length);
    // Без тире, двоеточия и «это» фраза может быть рассказом о случившемся:
    // «моя любимая певица умерла». Значением считается только узнаваемое слово
    // («синий», «зелёный чай») или название с заглавной буквы, в кавычках, с цифры.
    if (!match[2].trim()) {
      const words = tail.split(" ").map(word => word.replace(/[.,!«»"„“”'()]+/gu, ""));
      if (words.some(word => PREDICATE.test(word))) return null;
      const named = /^[«"„“'\dA-ZА-ЯЁ]/u.test(said) && words.length <= 5;
      if (!named && !kind.casual?.(tail)) return null;
    }
    const picked = cleanTaste(said);
    return picked ? { set: kind.key, value: picked } : null;
  }
  return null;
}

/** Слова-отклики: это не ответ, а реакция на сказанное ею. */
const REACTION = /^(?:круто|прикольно|класс(?:но)?|норм(?:ально)?|тоже|так\s+же|аналогично|красиво|мило|неплохо|соглас(?:ен|на)|вау|ого|понял[а]?|интересно|забавно|супер|здорово|отлично|мне\s+тоже|и\s+мне|и\s+я|я\s+тоже|у\s+меня\s+тоже|как\s+у\s+меня|как\s+у\s+(?:тебя|вас)|так(?:ой|ая|ое|ие)\s+же|то(?:т)?\s+же(?:\s+самое)?|та\s+же|те\s+же|(?:и\s+)?мо[йяеи](?:\s+тоже)?|точно|верно|ну\s+да|бывает|неожиданно|красивый|хороший|неплохой|отличный)(?:[\s,.!)]|$)/u;
/** «Хватит» — закончить анкету. */
const STOP = /^(?:вс[её][,\s]+)?(?:хватит|стоп|потом|позже|не\s+хочу|не\s+сейчас|законч(?:им|и)|достаточно|довольно|отмена|отбой|надоело)(?:\s+пока)?$/u;
/** «Не знаю», «не скажу», «любой», «все» — вопрос пропускается. */
const SKIP = /^(?:(?:я\s+)?не\s+(?:знаю|скажу|помню|выбрал[а]?|определил(?:ся|ась)|важно|могу\s+(?:выбрать|сказать))|(?:я\s+)?не\s+(?:люблю|ем|пью|слушаю|смотрю|читаю|играю|праздную)(?:\s.*)?|пропусти(?:ть|м)?|пропуск|дальше|следующий|нет(?:\s+так(?:ого|ой|их)|у|\s+любим(?:ого|ой|ых))?|никак(?:ой|ая|ое|ие)|ничего|никто|нигде|без\s+понятия|без\s+разницы|вс[её]\s+равно|хз|затрудняюсь|секрет|тайна|угадай|люб(?:ой|ая|ое|ые)|все|всяк(?:ий|ая|ое|ие)|разн(?:ый|ая|ое|ые)|неважно|какая\s+разница|зачем\s+(?:тебе|вам)|сложно\s+сказать|трудно\s+сказать)$/u;
/** Смех, междометия, «ок» и «спасибо»: реплика, а не ответ. */
const FILLER = /^(?:спасибо|спс|пасиб(?:о|ки)?|благодарю|ок(?:ей)?|ага|угу|понятно|ясно|хорошо|ладно|да|привет|пока|что|чего|че|чо|шо|а|э+|м+|ы+|о+|у+|ну+|хм+|гм+|кхм+|эм+|лол|кек|ору|ржу|жиза|в\s+смысле|зачем|почему|[ах]*(?:ах|ха)[ах]*|[ех]*(?:ех|хе)[ех]*|[их]*(?:их|хи)[их]*|[ыхг]*(?:ых|хы|гы)[ыхг]*|мда+|нда+|пф+|ой|ай|ух|эх|ох|блин|ну\s+да|ну\s+и|и\s+что|ну\s+ладно|ну\s+ок)$/u;
/** Вступление перед самим ответом: «у меня —», «я люблю», «наверное,», «тоже». */
const LEAD = /^(?:ну[,\s]+)?(?:а\s+)?(?:(?:наверное|наверно|пожалуй|думаю|конечно|скорее\s+всего)[,\s]+)?(?:(?:у\s+меня|мо[йяеи]|мне\s+нрав[ия]тся|я\s+(?:люблю|обожаю)|люблю|обожаю)(?:\s+(?:тоже|также))?(?:\s*[—–:-]\s*|\s+это\s+|\s+)|(?:тоже|также|это)\s+)?/u;
/** О смерти говорят не в анкете: такая реплика — разговор, и отвечать на неё «Запомнила» нельзя. */
const GRIEF = /^(?:умер(?:ла|ло|ли)?|погиб(?:ла|ло|ли)?|скончал(?:ся|ась)|похорон[а-я]*)$/u;
/** С этого слова начинается просьба, а не ответ: «расскажи сказку», «давай играть». */
const ORDER = /^(?:(?:расскажи|скажи|покажи|напиши|придумай|объясни|помоги|найди|переведи|сделай|дай|спой|нарисуй|включи|выключи|запомни|забудь|напомни|посоветуй|реши|посчитай|выбери|кинь|брось|сыграй|поиграй|обними|поцелуй|погладь|слушай|подожди|погоди|уйди|отстань|замолчи|заткнись|повтори|продолжай|продолжи|ответь|отвечай|поговори|прочитай|перескажи|расшифруй|посмотри|глянь|проверь|пришли|скинь|отправь|сочини|опиши|назови|перечисли|составь|предложи|подскажи|научи|удали|сотри|измени|поменяй|смени|будь|стань|желай|разбуди)(?:те)?|давай(?:те)?|хочу|можешь|можете|можно|умеешь|поиграем|сыграем)(?:[\s,.!?]|$)/u;
/**
 * Вопрос, обращение, отрицание. Проверяется только у встречного «а ваш?»: в
 * анкете так может называться фильм («Твоё имя», «Как приручить дракона»).
 */
const ASKING = /^(?:не|что|чего|чем|как|как(?:ой|ая|ое|ие)|где|куда|откуда|когда|почему|зачем|кто|кого|кому|сколько|чей|чья|чье|ты|тебе|тебя|тобой|вы|вам|вас|вами|тво[йяеи]|ваш[аеи]?|он|она|они|оно|мы|нам|нас|кстати|короче)(?:[\s,.!?]|$)/u;

/**
 * Ответ на вопрос анкеты: «хватит» — закончить, «не знаю» — пропустить, иначе —
 * само значение, без вступления («у меня — зелёный» → «зелёный»). Вопрос,
 * смех, «спасибо» и длинная речь — не ответ: null, фраза идёт обычным путём.
 */
export function readAnswer(text) {
  const raw = String(text ?? "").replace(/\s+/gu, " ").trim();
  let bare = raw.replace(/[.!…]+$/u, "").trim();
  let value = fold(bare);
  if (!value) return null;
  if (raw.endsWith("?") || raw.startsWith("/") || raw.length > MAX_VALUE || value.split(" ").length > 7) return null;
  // «Мой любимый сериал закрыли» — рассказ о другом, а не ответ на вопрос:
  // прямое «мой любимый цвет — синий» разобрано раньше, как просьба.
  if (/^(?:ну[,\s]+)?(?:а\s+)?(?:мо[йяеи]|у\s+меня)\s+(?:сам(?:ый|ая|ое|ые)\s+)?любим/u.test(value)) return null;
  // «Всё» — «на этом всё»; «все» без «ё» — «все подряд», то есть пропуск.
  if (/^всё$/iu.test(bare) || STOP.test(value)) return { stop: true };
  // Регистр и «ё» — как у человека: вступление срезается с исходной строки.
  const lead = value.length === bare.length ? value.match(LEAD)[0].length : 0;
  if (lead > 0 && lead < value.length) { value = value.slice(lead).trim(); bare = bare.slice(bare.length - value.length); }
  if (STOP.test(value)) return { stop: true };
  if (SKIP.test(value)) return { skip: true };
  if (FILLER.test(value) || ORDER.test(value)) return null;
  if (value.split(/[\s,.!]+/u).some(token => GRIEF.test(token))) return null;
  const reaction = value.match(REACTION);
  if (reaction && reaction[0].trim().length === value.length) return null;
  const picked = cleanTaste(bare);
  return picked ? { value: picked } : null;
}

/**
 * Ответ «к слову», на её встречное «а ваш?». Строже анкеты: слово должно быть
 * похоже на ответ именно на этот вопрос (`kind.casual`), а вступление «мой» и
 * «у меня» — отделено тире. Лучше не запомнить, чем записать любимым цветом
 * «уважаю» или «у меня вопрос».
 */
export function readCasual(text, kind = null) {
  const known = typeof kind === "string" ? tasteByKey(kind) : kind;
  if (!known?.casual) return null;
  const answer = readAnswer(text);
  if (!answer?.value) return null;
  if (/^(?:ну[,\s]+)?(?:а\s+)?(?:у\s+меня|мо[йяеи])\s+(?![—–:-]|это\s|тоже\s|также\s)/u.test(fold(text))) return null;
  const value = fold(answer.value);
  if (value.split(" ").length > 3 || /https?|www\./u.test(value)) return null;
  if (REACTION.test(value) || ASKING.test(value) || !known.casual(value)) return null;
  return answer;
}

export function createTastes({ store, now = () => Date.now() } = {}) {
  if (!store) throw new TypeError("createTastes needs store");

  async function read(userId) {
    const saved = await store.get(TASTE_KEY(userId)).catch(() => null);
    const items = saved?.items && typeof saved.items === "object" ? saved.items : {};
    const out = {};
    for (const { key } of TASTES) {
      const value = cleanTaste(items[key]?.v);
      if (value) out[key] = { v: value, shared: items[key].shared === true };
    }
    return out;
  }

  /** Что видно в этом месте: в группе — только названное при всех. */
  async function list(userId, { inGroup = false } = {}) {
    const items = await read(userId);
    return TASTES.filter(item => items[item.key] && (!inGroup || items[item.key].shared)).map(item => ({ key: item.key, title: item.title, value: items[item.key].v }));
  }

  async function get(userId, key, place = {}) {
    return (await list(userId, place)).find(item => item.key === key)?.value ?? "";
  }

  async function set(userId, key, value, { inGroup = false } = {}) {
    const clean = cleanTaste(value);
    if (!BY_KEY.has(key) || !clean) return { ok: false, code: "bad_value" };
    const items = await read(userId);
    const before = items[key]?.v ?? "";
    // Сказанное при всех остаётся общим, даже если потом повторено в личке.
    items[key] = { v: clean, shared: inGroup || (items[key]?.shared === true && before.toLowerCase() === clean.toLowerCase()) };
    const kept = await store.set(TASTE_KEY(userId), { items, at: now() }).then(result => result !== false).catch(() => false);
    return kept ? { ok: true, value: clean, before } : { ok: false, code: "storage_unavailable" };
  }

  async function drop(userId, key) {
    const items = await read(userId);
    if (!items[key]) return { ok: true, had: false };
    delete items[key];
    const kept = await store.set(TASTE_KEY(userId), { items, at: now() }).then(result => result !== false).catch(() => false);
    return kept ? { ok: true, had: true } : { ok: false, code: "storage_unavailable" };
  }

  async function clear(userId) {
    const had = Object.keys(await read(userId)).length;
    const kept = await store.set(TASTE_KEY(userId), { items: {}, at: now() }).then(result => result !== false).catch(() => false);
    return kept ? { ok: true, had } : { ok: false, code: "storage_unavailable" };
  }

  /** Следующий вопрос анкеты: первое, чего она не знает и что ещё не пропущено. */
  async function next(userId, { skipped = [] } = {}) {
    const items = await read(userId);
    return TASTES.find(item => !items[item.key] && !skipped.includes(item.key)) ?? null;
  }

  // ── вопрос, на который она ждёт ответа ──────────────────────────────────
  async function asking(chatId, userId) {
    const saved = await store.get(TASTE_ASK_KEY(chatId, userId)).catch(() => null);
    if (!saved?.kind || !BY_KEY.has(saved.kind)) return null;
    // Встречный вопрос «а ваш?» ждёт недолго: через три минуты слово уже о другом.
    if (now() - Number(saved.at) > (saved.casual ? TASTE_CASUAL_TTL_MS : saved.evening ? TASTE_EVENING_TTL_MS : TASTE_ASK_TTL_MS)) return null;
    return { kind: saved.kind, casual: saved.casual === true, evening: saved.evening === true, at: Number(saved.at) || 0, skipped: Array.isArray(saved.skipped) ? saved.skipped.filter(key => BY_KEY.has(key)) : [] };
  }
  const ask = (chatId, userId, kind, { skipped = [], casual = false, evening = false } = {}) => store.set(TASTE_ASK_KEY(chatId, userId), { kind, skipped, ...(casual ? { casual: true } : {}), ...(evening ? { evening: true } : {}), at: now() }).then(result => result !== false).catch(() => false);
  const rest = (chatId, userId) => store.set(TASTE_ASK_KEY(chatId, userId), { kind: "", at: 0 }).then(result => result !== false).catch(() => false);

  return { list, get, set, drop, clear, next, asking, ask, rest };
}

// ── вопрос вечера ────────────────────────────────────────────────────────
const EV_TIME = "(?:\\s+в\\s+(\\d{1,2})(?:[:.](\\d{2}))?(?:\\s*(?:час(?:а|ов)?|ч))?(?:\\s+вечера)?)?";
const EV_EVERY = "(?:\\s+(?:каждый\\s+(?:день|вечер)|по\\s+вечерам|ежедневно))?";
const EVENING_ON = [
  new RegExp(`^(?:задавай|спрашивай|присылай|шли|включи)(?:те)?\\s+(?:мне\\s+)?вопрос(?:ы)?\\s+вечера${EV_EVERY}${EV_TIME}$`, "u"),
  new RegExp(`^вопрос(?:ы)?\\s+вечера\\s+(?:каждый\\s+(?:день|вечер)|по\\s+вечерам|ежедневно)${EV_TIME}$`, "u"),
  new RegExp(`^(?:спрашивай|расспрашивай)(?:те)?\\s+меня\\s+(?:о\\s+любимом\\s+)?по\\s+вечерам${EV_TIME}$`, "u"),
];
const EVENING_OFF = /^(?:не\s+(?:задавай|спрашивай|присылай|шли|надо|нужно)|выключи|отключи|убери|отмени|хватит)(?:те)?\s+(?:больше\s+)?(?:мне\s+)?вопрос(?:ы|а|ов)?\s+вечера$|^не\s+(?:спрашивай|расспрашивай)(?:те)?\s+меня\s+по\s+вечерам$/u;

/**
 * «Задавай мне вопрос вечера [в 21:00]», «не задавай вопрос вечера».
 * Возвращает `{ on: true, hour, minute }`, `{ on: false }` или null.
 * Час до полудня понимается как вечерний: «в 9» — это 21:00.
 */
export function parseEvening(text) {
  const value = fold(String(text ?? "")).replace(/\s+/gu, " ").trim().replace(/[.!?…]+$/u, "").trim();
  if (!value || value.length > 70) return null;
  if (EVENING_OFF.test(value)) return { on: false };
  for (const pattern of EVENING_ON) {
    const found = value.match(pattern);
    if (!found) continue;
    let hour = found[1] == null ? EVENING_HOUR : Number(found[1]);
    const minute = Number(found[2]) || 0;
    if (hour >= 1 && hour < 12) hour += 12;
    if (hour > 23 || hour < 12 || minute > 59) return null;
    return { on: true, hour, minute };
  }
  return null;
}

// ── что у двоих общего ───────────────────────────────────────────────────
// «С Машей», «с @masha», «с ним» — одно слово: «…общего с этим миром» — уже разговор.
const WHOM = "(?:\\s+с\\s+(?:этим\\s+человеком|[@\\p{L}\\d_]{2,32}))?";
const COMMON = [
  new RegExp(`^(?:а\\s+)?что\\s+у\\s+(?:нас|меня)${WHOM}\\s+общего$`, "u"),
  new RegExp(`^(?:а\\s+)?что\\s+у\\s+(?:нас|меня)\\s+общего${WHOM}$`, "u"),
  new RegExp(`^(?:а\\s+)?что\\s+общего\\s+у\\s+(?:нас|меня)${WHOM}$`, "u"),
  /^сравни(?:те)?\s+(?:нас|наши\s+(?:анкеты|вкусы)|меня\s+с\s+(?:ним|ней))$/u,
  /^(?:а\s+)?(?:у\s+нас|мы)\s+(?:есть\s+)?(?:что-то|что-нибудь|хоть\s+что-то)\s+общее$/u,
];
/** «Что у нас общего?», «сравни нас» — слова о сравнении двух анкет. С кем — решает сердце: по ответу на сообщение. */
export function parseCommon(text) {
  const value = fold(String(text ?? "")).replace(/\s+/gu, " ").trim().replace(/[.!?…]+$/u, "").trim();
  if (!value || value.length > 70) return null;
  return COMMON.some(pattern => pattern.test(value)) ? { common: true } : null;
}

/**
 * Сравнение двух списков любимого (`[{ key, title, value }]`).
 * `same` — оба назвали одно и то же; `both` — оба назвали, но разное.
 * Без оценок и процентов: что совпало, то и названо.
 */
export function commonOf(mine, theirs) {
  const other = new Map((Array.isArray(theirs) ? theirs : []).map(item => [item.key, item]));
  const same = [], both = [];
  for (const item of Array.isArray(mine) ? mine : []) {
    const pair = other.get(item.key);
    if (!pair) continue;
    const short = item.title.replace(/^любим\S+\s+/u, "");
    if (fold(item.value) === fold(pair.value)) same.push({ key: item.key, title: short, value: item.value });
    else both.push({ key: item.key, title: short, a: item.value, b: pair.value });
  }
  return { same, both };
}
