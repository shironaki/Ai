const kindOf = (noun) => TASTES.find(item => item.pattern.test(noun)) ?? null;
const NOUN = "[а-я]+(?:\\s+года)?";
const ADJ = "(?:сам(?:ый|ая|ое|ые)\\s+)?любим(?:ый|ая|ое|ые)";
