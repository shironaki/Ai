/**
 * Намерения: закрытый список того, что сердце действительно делает.
 *
 * Команда — интерфейс для машины: её надо помнить, она требует точного слова и
 * знака. У Аи есть язык, поэтому вход — речь, а команда остаётся аварийным
 * выходом.
 *
 * Главное правило: **модель ничего не исполняет**. Она только разговаривает.
 * Здесь слова разбираются правилами, поэтому «запомни …» всегда означает одно
 * и то же действие, а «забань его» — никогда не означает бан: наказания
 * исполняет сестра и только по своим правилам.
 *
 * Три состояния ответа:
 *   sure   — поняла точно, действую и говорю, что сделала;
 *   maybe  — поняла половину, задаю один вопрос вместо догадки;
 *   null   — это не просьба, а разговор: идёт к модели.
 */
