/**
 * Мягкая чистка: кавычки, вежливость, обращение в начале, хвостовая
 * пунктуация — но регистр и «ё» остаются. По этой строке берётся то, что
 * человек просил запомнить: раньше факт сохранялся в нижнем регистре, и
 * «Берлин» превращался в «берлин».
 */
export function soften(text, { keepQuotes = false } = {}) {
  let value = String(text ?? "");
  if (keepQuotes) {
    // Кавычки снимаются, только когда в них взята вся фраза целиком.
    const wrapped = value.trim().match(/^[«“"']([^«»“”"]*)[»”"']$/u);
    if (wrapped) value = wrapped[1];
  } else {
    value = value.replace(/[«»“”"']/gu, " ");
  }
  return value
    .replace(/(?:^|\s)(?:пожалуйста|плиз|будь\s+добра|будь\s+добр|будьте\s+добры)(?=\s|$)/giu, " ")
    // Обращение в начале — не часть просьбы: «слушай, запомни» и «запомни»
    // это одно и то же действие.
    .replace(/^(?:аи|слушай|эй|ну|окей|ок|ладно|короче)[\s,!:]+(?=\S)/iu, "")
    .replace(/\s+/gu, " ")
    .replace(/^[\s\-–—•*]+/u, "")
    .replace(/[\s.,!?;:…]+$/u, "")
    .trim();
}

/**
 * Приведение к виду, по которому можно сравнивать: то же, что `soften`, плюс
 * регистр и «ё». Без этого «Запомни!» и «запомни» — разные строки.
 */
export function normalize(text) {
  return soften(String(text ?? "").toLowerCase().replace(/ё/gu, "е"));
}

const sure = (intent, arg = null) => ({ intent, confidence: "sure", arg });
const maybe = (intent, question) => ({ intent, confidence: "maybe", question });

/**
 * Наказания, роли, доступ и деньги — в повелительной форме. Вопрос «что такое
 * мут?» и рассказ «меня забанили» сюда не попадают: это разговор.
 */
const DIRECT = "(?:забань|разбань|замуть|размуть|замьють|кикни|выгони|заварнь|разварнь|понизь|повысь|оплати|купи)";
const VERB = "(?:дай|выдай|выпиши|влепи|поставь|сделай|назначь|сними|убери|отмени|верни|забери|подари|начисли|спиши|переведи|отправь|измени|поменяй|смени|перепиши)";
const TARGET = "(?:бан|мут|кик|варн|предупреждени[еяй]|рол[ьиюей]|вип|vip|админ|модер|правила|деньги|денег|рубл|звезд|монет|баланс|оплат|доступ|уровень|уровня|опыт)";
const NOT_MINE = new RegExp(
  `^(?:${DIRECT}(?=$|[\\s,.!?;:])` +
  `|${VERB}(?:\\s+(?!про(?=\\s)|о(?=\\s)|об(?=\\s)|насчет(?=\\s)|по(?=\\s))\\S+){0,3}?\\s+${TARGET}` +
  `|(?:бан|мут|кик|варн)\\s+(?:ему|ей|им|этому|этой|его|ее|@\\S+))`, "u",
);

const TEACH = [
  ["rule", /^(?:правило\s*[:—-]|запомни\s+правило\s*[:,—-]?|впредь[\s,:—-]|на\s+будущее\s*[:,—-]|всегда\s*[:—-]|никогда\s*[:—-])\s*(.+)$/iu],
  ["lesson", /^(?:урок\s*[:—-]|запомни\s+урок\s*[:,—-]?|так\s+не\s+надо\s*[:,—-]?|не\s+надо\s+так\s*[:,—-]?|так\s+нельзя\s*[:,—-])\s*(.+)$/iu],
  ["fact", /^(?:знай\s*[:,—-]|запомни\s+знание\s*[:,—-]?|к\s+сведению\s*[:,—-])\s*(.+)$/iu],
];

/**
 * Разобрать просьбу. Возвращает `{ intent, confidence, arg }`, `{ confidence:
 * "maybe", question }` или `null` — если это обычная фраза разговора.
 */
export function parseIntent(text) {
  const value = normalize(text);
  if (!value) return null;
  // Та же фраза с исходным регистром и кавычками: из неё берутся слова
  // человека — «не называй меня «другом»» должно сохраниться как сказано.
  const soft = soften(text, { keepQuotes: true });

  // ── уроки: чему её учат ───────────────────────────────────────────────
  for (const [kind, pattern] of TEACH) {
    const taught = soft.match(pattern);
    if (taught && taught[1].trim().length >= 3) return sure("teach", { kind, text: taught[1].trim() });
  }
  if (/^(?:урок|правило|знай|впредь|так не надо)$/u.test(value)) {
    return maybe("teach", "Чему именно научить? Одной фразой: «урок: …» или «правило: …».");
  }
  if (/^(?:(?:покажи|перечисли)\s+)?(?:(?:твои|свои|все)\s+)?(?:уроки|список\s+уроков)$|^какие\s+у\s+тебя\s+уроки$/u.test(value)) return sure("lessons");
  const unlearn = value.match(/^(?:забудь|отмени|удали|сотри)\s+(?:урок|правило|знание)\s+(?:номер\s+|№\s*)?(\d{1,4})$/u);
  if (unlearn) return sure("unlearn", { mode: "id", id: Number(unlearn[1]) });
  if (/^(?:откати|отмени|забудь)\s+(?:все\s+)?уроки\s+за\s+сегодня$/u.test(value)) return sure("unlearn", { mode: "today" });
  const judged = value.match(/^(прими|одобри|принять|отклони|отклонить)\s+урок\s+(?:номер\s+|№\s*)?(\d{1,4})$/u);
  if (judged) return sure("judge", { id: Number(judged[2]), accept: /^(?:прими|одобри|принять)$/u.test(judged[1]) });
  if (/^(?:чему\s+ты\s+(?:научилась|учишься|научилась\s+за\s+\S+)|что\s+ты\s+(?:усвоила|выучила|поняла)|чему\s+научилась)$/u.test(value)) return sure("learned");
  if (/^(?:почему\s+ты\s+так\s+(?:ответила|сказала|решила|думаешь)|почему\s+так|откуда\s+ты\s+это\s+(?:знаешь|взяла)|на\s+что\s+ты\s+опиралась|с\s+чего\s+ты\s+(?:это\s+)?взяла)$/u.test(value)) {
    return sure("why_answer");
  }

  // ── напоминания ───────────────────────────────────────────────────────
  // Время разбирает сердце: ему нужны часы и пояс. Здесь — только «это
  // просьба напомнить», со словами человека как есть.
  // «Буди меня в 8» и «капсула времени на год: …» — те же напоминания: одно
  // повторяется, другое подписано как письмо себе.
  if (/^(?:напомни(?:те)?|напоминай(?:те)?|напомнишь|поставь(?:те)?\s+напоминание|(?:раз)?буди(?:те)?\s+(?:меня|нас)|капсул[ау]\s+времени|(?:закопай|запечатай|сделай|оставь)(?:те)?\s+капсулу)(?=$|[\s,:—-])/u.test(value)) {
    // Обращение и вежливость сняты, слова человека — как сказаны.
    return sure("remind", soft);
  }
  if (/^(?:(?:покажи|какие)\s+)?(?:мои\s+|у\s+меня\s+)?(?:напоминания|напоминалки)$|^(?:что|о\s+чем)\s+ты\s+(?:мне\s+)?(?:напомнишь|должна\s+напомнить)$|^список\s+напоминаний$/u.test(value)) return sure("reminders");
  const unremind = value.match(/^(?:отмени|удали|убери|забудь|сотри)\s+(?:напоминание|напоминалку)\s+(?:номер\s+|№\s*)?(\d{1,3})$/u);
  if (unremind) return sure("unremind", { index: Number(unremind[1]) });
  if (/^(?:отмени|удали|убери|забудь|сотри)\s+(?:все\s+)?(?:напоминания|напоминалки)$/u.test(value)) return sure("unremind", { index: null });
  if (/^(?:отмени|удали|убери)\s+(?:напоминание|напоминалку)$/u.test(value)) return maybe("unremind", "Какое именно? «мои напоминания» покажет список, затем «отмени напоминание 2».");

  // ── слово хозяину ─────────────────────────────────────────────────────
  // Чужая личка хозяину не пересказывается. Передаётся только то, что
  // человек сам попросил передать, — и ровно его словами.
  const mail = soft.match(/^(?:передай(?:те)?|напиши(?:те)?|сообщи(?:те)?|скажи(?:те)?)\s+(?:(?:своему|твоему|вашему)\s+)?(?:хозяину|владельцу|создателю)\s*[:,—-]?\s*(?:,?\s*что\s+)?(.+)$/iu);
  if (mail && mail[1].trim().length >= 3) return sure("tell_owner", mail[1].trim());
  if (/^(?:передай|напиши|сообщи|скажи)(?:те)?\s+(?:(?:своему|твоему|вашему)\s+)?(?:хозяину|владельцу|создателю)$/u.test(value)) {
    return maybe("tell_owner", "Что передать? Одной фразой: «передай хозяину: …».");
  }

  // ── память ────────────────────────────────────────────────────────────
  // «запомни …» — всегда просьба; «запиши»/«сохрани» — только со знаком или
  // «что»: «сохрани спокойствие» — это разговор, а не запись.
  const remembered = soft.match(/^запомни(?:\s+себе)?(?:\s*[:,—-]\s*|\s+)(.+)$/iu)
    ?? soft.match(/^(?:запиши|сохрани)(?:\s+себе)?(?:\s*[:,—-]\s*(.+)|\s+(что\s+.+))$/iu);
  const fact = (remembered?.[1] ?? remembered?.[2] ?? "").trim();
  // «запомни это» без продолжения — не факт о человеке, а просьба, которую
  // поняли наполовину: спрашиваем, а не записываем пустоту.
  if (fact && !/^(?:это|это\s+себе|себе|вот\s+это)$/iu.test(fact)) return sure("remember", fact);
  if (/^(?:запомни|запиши|сохрани)(?:\s+(?:это|это\s+себе|себе|вот\s+это))?$/u.test(value)) {
    return maybe("remember", "Что запомнить? Одной фразой: «запомни, …».");
  }

  if (new RegExp(
    "^(?:что\\s+(?:ты|вы)\\s+(?:обо\\s+мне\\s+)?(?:помнишь|знаешь|помните|знаете)" +
    "|что\\s+у\\s+тебя\\s+(?:обо\\s+мне\\s+)?записано" +
    // Те же слова другим порядком (0.36.1): «что ты знаешь обо мне», «покажи память», «что ты запомнила».
    "|что\\s+(?:ты|вы)\\s+(?:помнишь|знаешь|помните|знаете|запомнила)\\s+(?:обо\\s+мне|про\\s+меня)" +
    "|что\\s+(?:обо\\s+мне|про\\s+меня)\\s+(?:помнишь|знаешь|запомнила)" +
    "|что\\s+у\\s+тебя\\s+записано\\s+(?:обо\\s+мне|про\\s+меня)" +
    "|что\\s+ты\\s+запомнила|покажи\\s+(?:мои\\s+)?(?:записи|память)|покажи,?\\s+что\\s+(?:ты\\s+)?(?:помнишь|запомнила)(?:\\s+обо\\s+мне)?" +
    "|мои\\s+записи|что\\s+помнишь)$", "u",
  ).test(value)) return sure("memories");

  // Забыть можно последнее, одну запись по номеру, все записи — или всё о
  // себе целиком. Последнее необратимо, поэтому требует подтверждения.
  if (/^(?:да[,\s]+)?(?:удали|сотри|забудь)\s+вс[её]$/iu.test(soft) && /^да/u.test(value)) return sure("forget", { mode: "confirm" });
  if (/^(?:(?:удали|сотри|забудь)\s+(?:все\s+)?(?:обо\s+мне|про\s+меня|мои\s+данные|все\s+мои\s+данные)|забудь\s+меня|сотри\s+меня)$/u.test(value)) {
    return sure("forget", { mode: "everything" });
  }
  if (/^(?:забудь|сотри|удали)\s+(?:все|все\s+записи|все\s+заметки)$|^(?:очисти|сотри|удали|обнули|сбрось|почисти)\s+(?:всю\s+)?(?:свою\s+)?память$/u.test(value)) return sure("forget", { mode: "all" });
  if (/^(?:забудь|сотри|удали)\s+(?:это|последнее|последнюю\s+запись|последнюю)$/u.test(value)) return sure("forget", { mode: "last" });
  // «Не запоминай это» сразу после её «запомнила» — о последней записи (0.36.1).
  if (/^(?:это\s+)?не\s+(?:надо\s+|нужно\s+)?(?:это(?:го)?\s+)?(?:запоминай|записывай|запоминать|записывать)(?:\s+это(?:го)?)?$/u.test(value)) return sure("forget", { mode: "last" });
  if (/^(?:забудь|сотри|удали)$/u.test(value)) {
    return maybe("forget", "Что именно забыть — последнее, одну запись или всё? «забудь это», «забудь 2» или «забудь всё».");
  }
  const forgetOne = value.match(/^(?:забудь|сотри|удали)\s+(?:номер\s+|запись\s+)?(\d{1,3})$/u);
  if (forgetOne) return sure("forget", { mode: "index", index: Number(forgetOne[1]) });
  if (/^(?:забудь|сотри|удали)(?:\s|$)/u.test(value)) {
    return maybe("forget", "Что именно забыть — последнее, одну запись или всё? «забудь это», «забудь 2» или «забудь всё».");
  }

  // ── что у меня есть ───────────────────────────────────────────────────
  if (/^(?:(?:покажи|открой)\s+)?(?:мне\s+)?(?:мой\s+)?(?:профиль|профиля|карточку|карточка)$/u.test(value)) {
    return sure("profile");
  }
  if (/^(?:(?:покажи|открой)\s+)?(?:мой\s+)?(?:инвентарь|награды|что\s+у\s+меня\s+есть)$/u.test(value)) {
    return sure("inventory");
  }
  if (new RegExp(
    "^(?:как\\s+(?:ты|вы)\\s+(?:ко\\s+мне\\s+)?относи(?:шься|тесь)" +
    "|что\\s+ты\\s+ко\\s+мне\\s+чувствуешь" +
    "|мы\\s+(?:друзья|близки)" +
    "|наши\\s+отношения|что\\s+между\\s+нами|какие\\s+у\\s+нас\\s+отношения)$", "u",
  ).test(value)) return sure("relationship");

  // «Вы и Аи» — её собственная карточка: обращение, дни знакомства, память.
  if (/^(?:(?:покажи|открой)\s+)?(?:вы\s+и\s+аи|мы\s+с\s+тобой|мы\s+с\s+вами|наша\s+карточка|карточк[ау]\s+отношений)$/u.test(value)) return sure("card");

  // ── игра и сбор ───────────────────────────────────────────────────────
  // Что именно сказано об игре, разбирает сама игра: список, название,
  // кубик, монетка, «выбери за меня».
  const game = parseGame(value, soft);
  if (game) return game;
  if (/^(?:созови|собери)\s+(?:всех|народ|людей)(?:\s+в\s+чат)?$/u.test(value)) return sure("summon");

  // ── о себе: кто она, что умеет, какая сборка, что нового ──────────────
  if (/^(?:что\s+(?:ты|вы)\s+(?:умеешь|можешь|умеете|можете)|что\s+умеешь|твои\s+(?:умения|возможности)|помощь|справка|help|меню|menu|команды|список\s+команд|как\s+(?:тобой|с\s+тобой)\s+(?:пользоваться|общаться))$/u.test(value)) {
    return sure("help");
  }
  if (/^(?:кто\s+ты|ты\s+кто|кто\s+ты\s+такая|что\s+ты\s+такое|ты\s+(?:бот|человек|робот|нейросеть)|ты\s+живая)$/u.test(value)) return sure("whoami");
  if (/^(?:какая\s+(?:у\s+тебя\s+)?(?:версия|сборка)|версия|сборка|твоя\s+(?:версия|сборка)|ты\s+обновилась)$/u.test(value)) return sure("version");
  if (/^(?:что\s+нового\s+у\s+(?:юи|сестры)|новости\s+(?:юи|сестры))$/u.test(value)) return sure("sister_news");
  if (/^(?:что\s+нового(?:\s+у\s+тебя)?(?:\s+в\s+(?:этой\s+|новой\s+)?(?:сборке|версии))?|какие\s+новости|что\s+(?:изменилось|поменялось|добавили|добавилось|обновилось)|что\s+в\s+тебе\s+нового|что\s+нового\s+в\s+тебе|что\s+(?:ты\s+)?теперь\s+умеешь|что\s+нового\s+(?:ты\s+)?умеешь|что\s+в\s+(?:этой\s+|новой\s+)?(?:сборке|версии)(?:\s+нового)?)$/u.test(value)) return sure("news");
  if (/^(?:статус|твой\s+статус|состояние|диагностика|самопроверка|проверь\s+себя|как\s+твое\s+здоровье)$/u.test(value)) return sure("status");
  if (/^(?:проверь|проба|испытай)\s+(?:свои\s+)?(?:мозг(?:и|ов)|модел(?:и|ей)|провайдер(?:ы|ов|а)|запасн(?:ые|ых|ой)(?:\s+(?:мозги|модели))?|gigachat|гигачат)$/u.test(value)) return sure("brains_check");

  // ── границы ───────────────────────────────────────────────────────────
  if (/^(?:без\s+флирта|не\s+флиртуй(?:\s+со\s+мной)?|хватит\s+флиртовать)$/u.test(value)) return sure("no_flirt");
  if (/^(?:можно\s+(?:флиртовать|флирт|заигрывать)(?:\s+со\s+мной)?|(?:по)?флиртуй\s+со\s+мной|давай\s+(?:по)?флиртовать|можешь\s+(?:со\s+мной\s+)?(?:флиртовать|заигрывать)(?:\s+со\s+мной)?|разрешаю\s+флирт(?:овать)?|верни\s+флирт|с\s+флиртом)$/u.test(value)) return sure("yes_flirt");
  // Ревность (0.35.0): «не ревнуй» успокаивает на раз (словарь), «без ревности» — выключает совсем.
  if (/^(?:без\s+ревности|никогда\s+(?:меня\s+|больше\s+)?не\s+ревнуй|не\s+ревнуй\s+(?:меня\s+)?(?:больше\s+)?(?:никогда|совсем|вообще)|больше\s+(?:никогда\s+)?(?:меня\s+)?не\s+ревнуй|перестань\s+(?:меня\s+)?ревновать\s+(?:совсем|навсегда|вообще)|(?:выключи|отключи|убери)\s+ревность)$/u.test(value)) return sure("no_jealous");
  if (/^(?:можешь\s+(?:меня\s+)?ревновать|можно\s+(?:меня\s+)?ревновать|ревнуй\s+меня|(?:включи|верни)\s+ревность|разрешаю\s+(?:меня\s+)?ревновать|ревнуй\s+на\s+здоровье|с\s+ревностью)$/u.test(value)) return sure("yes_jealous");
  if (/^(?:не\s+реагируй(?:\s+на\s+(?:каждое\s+)?(?:слово|сообщение|все))?|хватит\s+реагировать|не\s+ставь\s+реакции|без\s+реакций)$/u.test(value)) {
    return sure("no_reactions");
  }
  if (/^(?:не\s+пиши\s+(?:мне\s+)?ночью|не\s+беспокой(?:\s+меня)?\s+ночью)$/u.test(value)) return sure("no_night");

  // ── почему молчала ────────────────────────────────────────────────────
  // «Чего молчишь?», «ты меня игнорируешь?» — тот же вопрос: ответ — настоящая причина из записи.
  if (new RegExp(
    "^(?:почему\\s+ты\\s+(?:мне\\s+)?(?:(?:ночью|вчера|утром|днем|вечером|сегодня|тогда|так\\s+долго|весь\\s+день|всю\\s+ночь)\\s+)?(?:не\\s+ответила|не\\s+отвечала|молчала|молчишь|не\\s+пишешь|не\\s+писала|не\\s+отвечаешь)(?:\\s+(?:ночью|вчера|утром|днем|вечером|сегодня|так\\s+долго|мне))?" +
    "|(?:почему|чего|что|зачем)\\s+(?:ты\\s+)?(?:молчишь|молчала)" +
    "|(?:(?:почему|зачем)\\s+)?(?:ты\\s+)?(?:меня\\s+)?(?:игнорируешь|игноришь)(?:\\s+меня)?" +
    "|почему\\s+нет\\s+ответа|почему\\s+молчание)$", "u",
  ).test(value)) return sure("whyquiet");

  // ── не моё: наказания, роли и деньги ──────────────────────────────────
  // Это не лень и не скромность. Ошибка распознавания здесь = наказан
  // невиновный или списаны деньги, поэтому сердце такие просьбы не исполняет
  // даже при полном понимании.
  // «Переведи 5000 рублей в доллары» — пересчёт по курсу, а не перевод денег.
  if (NOT_MINE.test(value) && detectSource(value)?.kind !== "convert") return sure("not_mine", value);

  return null;
}
