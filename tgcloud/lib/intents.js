/**
 * Приведение к виду, по которому можно сравнивать: регистр, «ё», кавычки,
 * хвостовая пунктуация. Без этого «Запомни!» и «запомни» — разные строки.
 */
export function normalize(text) {
  return String(text ?? "")
    .toLowerCase()
    .replace(/ё/gu, "е")
    .replace(/[«»“”"']/gu, " ")
    .replace(/(?:^|\s)(?:пожалуйста|плиз|будь\s+добра|будь\s+добр)(?=\s|$)/gu, " ")
    // Обращение в начале — не часть просьбы: «слушай, запомни» и «запомни»
    // это одно и то же действие.
    .replace(/^(?:аи|слушай|эй|ну|окей|ок|ладно|короче)[\s,!:]+(?=\S)/u, "")
    .replace(/\s+/gu, " ")
    .replace(/^[\s\-–—•*]+/u, "")
    .replace(/[\s.,!?;:…]+$/u, "")
    .trim();
}

const sure = (intent, arg = null) => ({ intent, confidence: "sure", arg });
const maybe = (intent, question) => ({ intent, confidence: "maybe", question });

const END = "(?:[\\s,.!?;:]|$)";

/**
 * Разобрать просьбу. Возвращает `{ intent, confidence, arg }`, `{ confidence:
 * "maybe", question }` или `null` — если это обычная фраза разговора.
 */
export function parseIntent(text) {
  const value = normalize(text);
  if (!value) return null;

  // ── память ────────────────────────────────────────────────────────────
  const remembered = value.match(/^(?:запомни|запиши|сохрани)(?:\s+себе)?(?:\s*[:,—-]\s*|\s+)(.+)$/u);
  // «запомни это» без продолжения — не факт о человеке, а просьба, которую
  // поняли наполовину: спрашиваем, а не записываем пустоту.
  if (remembered && !/^(?:это|это\s+себе|себе|вот\s+это)$/u.test(remembered[1].trim())) {
    return sure("remember", remembered[1].trim());
  }
  if (/^(?:запомни|запиши|сохрани)(?:\s+(?:это|это\s+себе|себе|вот\s+это))?$/u.test(value)) {
    return maybe("remember", "Что запомнить? Скажи одной фразой: «запомни, …».");
  }

  if (new RegExp(
    "^(?:что\\s+ты\\s+(?:обо\\s+мне\\s+)?(?:помнишь|знаешь)" +
    "|что\\s+у\\s+тебя\\s+(?:обо\\s+мне\\s+)?записано" +
    "|мои\\s+записи|что\\s+помнишь)$", "u",
  ).test(value)) return sure("memories");

  // «Забудь» без продолжения непонятно: всё или одну запись? Один вопрос
  // дешевле, чем стереть память, которую просили хранить.
  if (/^(?:забудь|сотри|удали)\s+(?:это|все|все\s+обо\s+мне|обо\s+мне|про\s+меня)$/u.test(value)) {
    return sure("forget", { mode: "all" });
  }
  if (/^(?:забудь|сотри|удали)$/u.test(value)) {
    return maybe("forget", "Что именно забыть — всё или одну запись? Скажи «забудь всё» или «забудь 2».");
  }
  const forgetOne = value.match(/^(?:забудь|сотри|удали)\s+(?:номер\s+)?(\d{1,3})$/u);
  if (forgetOne) return sure("forget", { mode: "index", index: Number(forgetOne[1]) });
  if (/^(?:забудь|сотри|удали)(?:\s|$)/u.test(value)) {
    return maybe("forget", "Что именно забыть — всё или одну запись? Скажи «забудь всё» или «забудь 2».");
  }

  // ── что у меня есть ───────────────────────────────────────────────────
  if (/^(?:(?:покажи|открой)\s+)?(?:мне\s+)?(?:мой\s+)?(?:профиль|профиля|карточку|карточка)$/u.test(value)) {
    return sure("profile");
  }
  if (/^(?:(?:покажи|открой)\s+)?(?:мой\s+)?(?:инвентарь|награды|что\s+у\s+меня\s+есть)$/u.test(value)) {
    return sure("inventory");
  }
  if (new RegExp(
    "^(?:как\\s+ты\\s+(?:ко\\s+мне\\s+)?относишься" +
    "|что\\s+ты\\s+ко\\s+мне\\s+чувствуешь" +
    "|мы\\s+(?:друзья|близки)" +
    "|наши\\s+отношения|что\\s+между\\s+нами|какие\\s+у\\s+нас\\s+отношения)$", "u",
  ).test(value)) return sure("relationship");

  // ── игра и сбор ───────────────────────────────────────────────────────
  if (/^(?:давай\s+)?(?:сыграем|поиграем|устроим\s+игру|викторину?)$/u.test(value)) return sure("play");
  if (/^(?:созови|собери)\s+(?:всех|народ|людей)(?:\s+в\s+чат)?$/u.test(value)) return sure("summon");

  // ── новости и версия ──────────────────────────────────────────────────
  if (/^(?:что\s+нового|какие\s+новости|что\s+изменилось|какая\s+(?:у\s+тебя\s+)?версия|версия|сборка)$/u.test(value)) {
    return sure("news");
  }

  // ── границы ───────────────────────────────────────────────────────────
  if (/^(?:без\s+флирта|не\s+флиртуй(?:\s+со\s+мной)?|хватит\s+флиртовать)$/u.test(value)) return sure("no_flirt");
  if (/^(?:не\s+реагируй(?:\s+на\s+(?:каждое\s+)?(?:слово|сообщение|все))?|хватит\s+реагировать|не\s+ставь\s+реакции)$/u.test(value)) {
    return sure("no_reactions");
  }
  if (/^(?:не\s+пиши\s+(?:мне\s+)?ночью|не\s+беспокой(?:\s+меня)?\s+ночью)$/u.test(value)) return sure("no_night");

  // ── почему молчала ────────────────────────────────────────────────────
  if (new RegExp(
    "^(?:почему\\s+ты\\s+(?:мне\\s+)?(?:не\\s+ответила|молчала|молчишь|не\\s+пишешь)" +
    "|почему\\s+нет\\s+ответа|почему\\s+молчание)$", "u",
  ).test(value)) return sure("whyquiet");

  // ── не моё: наказания, роли и деньги ──────────────────────────────────
  // Это не лень и не скромность. Ошибка распознавания здесь = наказан
  // невиновный или списаны деньги, поэтому сердце такие просьбы не исполняет
  // даже при полном понимании.
  if (new RegExp(
    "^(?:забань|разбань|замуть|размуть|кикни|выгони|заварнь" +
    "|понизь|повысь|выдай\\s+(?:роль|варн|предупреждение)|сними\\s+(?:роль|варн|предупреждение)" +
    "|переведи\\s+(?:деньги|рубли|звезды)|купи|оплати)" + END, "u",
  ).test(value)) return sure("not_mine", value);

  return null;
}

