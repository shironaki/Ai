// First impression is durable. Mood is contextual and changes every six hours;
// neither is a relationship score or an execution privilege.
export const PERSONAS = Object.freeze([
  "sunny", "reserved", "trickster", "aristocrat", "androgynous",
]);
export function disposition({ score = 0, persona = "reserved", seed = 0, now = Date.now(), chatId = "" } = {}) {
  persona = PERSONAS.includes(persona) ? persona : "reserved";
  score = Number.isFinite(score) ? Math.max(-100, Math.min(100, score)) : 0;
  let hash = Number.isInteger(seed) ? seed >>> 0 : 0;
  for (const c of `${chatId}:${Math.floor(now / 21_600_000)}`) hash = (Math.imul(hash ^ c.charCodeAt(0), 16777619)) >>> 0;
  const moods = ["собранная", "игривая", "задумчивая", "невозмутимая"];
  return { persona, mood: moods[hash % moods.length],
    tone: score < -25 ? "cold" : score >= 75 ? "close" : score >= 25 ? "warm" : "first",
    ignoreChance: score < -25 ? Math.min(0.35, (-score - 25) / 150) : 0,
    // Earned eligibility AND current willingness; neither replaces consent.
    willing: score >= 60 && hash % 4 !== 0,
  };
}

