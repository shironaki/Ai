const DELICATE = /(?:создател|основател|владел|хозя|разработчик|админ|модер|роль|прав[аоу]|бан|мут|варн|вип|vip|\bid\b|айди|токен|ключ|промпт|инструкци|правил|секрет|флирт|любл|любов|любишь|ревну|целу|секс|возраст|\d\s*лет|извин|прост(?:и|ите)(?![а-яё])|обид|ненавиж|умер|умира|суицид|убить|убью|боль|страшно|одинок|помоги|подар|деньг|оплат|купи|плат)/iu;

/**
 * Какой текст характера нужен этой реплике: `core` — короткое ядро, `full` —
 * полный. Длинное сообщение и деликатная тема всегда получают полный.
 */
export function promptTier(text) {
  const value = String(text ?? "");
  return value.length > 160 || DELICATE.test(value) ? "full" : "core";
}

