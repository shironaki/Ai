/** Self-reported civil birthday; complete local calendar years, never verification.
 * Feb 29 reaches its anniversary on March 1 in a non-leap year.
 */
export function ageFromBirthday(date, at = Date.now(), timeZone) {
  const m = String(date ?? "").match(/^(\d{4})-(\d{2})-(\d{2})$/u);
  if (!m || !Number.isFinite(new Date(at).getTime())) return null;
  const birth = new Date(`${date}T00:00:00Z`);
  if (!Number.isFinite(birth.getTime()) || birth.toISOString().slice(0, 10) !== date || Number(m[1]) < 1900) return null;
  const today = calendarDate(at, timeZone);
  if (date > today) return null;
  return Number(today.slice(0, 4)) - Number(m[1]) - (today.slice(5) < date.slice(5) ? 1 : 0);
}
