/**
 * Комната Аи (0.37.0) — первый шаг идей 41 и 112–114, пока без мини-приложения.
 *
 * Её комната живёт сама по себе: за окном тот час, что у человека на часах; она занята тем, что
 * подсказывает настроение; кот Байт голоден, сыт, спит или шалит — смотря что с ним сегодня делали.
 * В комнату можно зайти словами («зайду к тебе», «как там Байт»), о Байте — позаботиться («погладить»,
 * «покормить», «поиграть»), ей — налить чаю, Колючку — полить. Забота засчитывается в отношения не чаще
 * раза в день. Вещи появляются сами — по дням знакомства и по заботе, а не за валюту (валюта и награды —
 * сторона Юи). Раз в день в личке — сценка с выбором из двух («Байт уронил Колючку»).
 *
 * Здесь разбор слов, правила и запись о комнате каждого человека. Слова — в словаре (запасы
 * «+комната:…»), голос и отправка — в `heart.js`. Мини-приложение (окно в ту же комнату) будет читать
 * то же самое состояние: поэтому здесь нет ни Telegram, ни текста ответа — только «что сейчас в комнате».
 */
const fold = (text) => String(text ?? "").toLowerCase().replace(/ё/gu, "е").replace(/[«»"“”„]/gu, "").replace(/[,;:—–-]+/gu, " ").replace(/\s+/gu, " ").trim().replace(/[\s.!?…)(]+$/u, "").trim();

