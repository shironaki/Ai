/**
 * Слова о комнате: `{ op }` или `null`. `op`: enter (зайти), cat (как Байт), plant (как Колючка), pet, feed, play, tea,
 * water, news, call (позвать Байта) и hurt — Байта хотят обидеть (она не даст).
 * `near: true` — человек только что был в комнате: тогда годятся и короткие слова (`{ op, loose: true }`).
 * Описание комнаты («какая у тебя комната», «что у тебя в комнате») остаётся словарю: там она рассказывает,
 * а здесь — показывает, что происходит сейчас.
 */
export function parseRoom(text, { near = false } = {}) {
  const said = fold(text).replace(/^(?:ну|а\s+ну|слушай|кстати)\s+/u, "");
  if (!said || said.length > 70) return null;
  for (const [op, rule] of RULES) if (rule.test(said)) return { op };
  if (near) for (const [op, rule] of LOOSE) if (rule.test(said)) return { op, loose: true };
  return null;
}

