/**
 * Сколько длятся рассвет и закат на рисунке. «Утро» начинается за сорок минут до восхода (небо уже светлеет) и идёт
 * два с половиной часа после него; «вечер» — закатный свет: пятьдесят минут до захода солнца и сорок после, пока
 * не стемнеет. Зимой день короткий — утро и вечер не заходят за его середину.
 */
export const SUN = Object.freeze({ dawn: 40 * 60_000, morning: 150 * 60_000, golden: 50 * 60_000, dusk: 40 * 60_000 });
/**
 * Какой свет за окном в момент `at`, если солнце сегодня встаёт в `sun.rise` и садится в `sun.set` (мс эпохи):
 * `{ light, left }` — слово из частей суток (им рисунок красит небо, комнату и лампу) и сколько осталось до
 * следующей перемены, мс. `null` — солнца не знаем (города нет, полярный день или ночь): свет идёт по часам.
 * До 0.47.0 свет шёл по часам всегда: в ноябре в пять вечера за окном комнаты был день, а в июне в семь — закат.
 */
export function lightAt(at, sun) {
  const rise = Number(sun?.rise), set = Number(sun?.set), when = Number(at);
  if (!Number.isFinite(rise) || !Number.isFinite(set) || !Number.isFinite(when) || set - rise < 3_600_000) return null;
  const middle = (rise + set) / 2;
  const edges = [[rise - SUN.dawn, "утро"], [Math.min(rise + SUN.morning, middle), "день"], [Math.max(set - SUN.golden, middle), "вечер"], [set + SUN.dusk, "ночь"]];
  const light = edges.filter(([edge]) => when >= edge).at(-1)?.[1] ?? "ночь";
  // После заката следующая перемена — завтрашний рассвет: он почти там же, где сегодняшний, плюс сутки.
  const coming = edges.find(([edge]) => edge > when)?.[0] ?? edges[0][0] + 24 * 3_600_000;
  return { light, left: Math.round(coming - when) };
}
/**
 * Какой пометкой брать слова об окне, когда свет за ним разошёлся с часами (0.47.0). Слова об окне начинаются с
 * «Утро.», «Вечер.», «Ночь.» — по часам человека; а рисунок теперь красит небо по солнцу. Сошлись — пометка части
 * суток, как раньше. Разошлись — три случая со своими словами:
 *   «затемно»  — утро по часам, а за окном ещё ночь (зима);
 *   «стемнело» — день или вечер по часам, а за окном уже ночь (осень, зима, весна — почти каждый вечер);
 *   «светло»   — вечер или ночь по часам, а за окном день (лето).
 * Закат среди дня и рассвет среди ночи говорятся словами вечера и утра: они о небе, а не о часах.
 */
export function windowTag(part, light) {
  if (!["утро", "день", "вечер", "ночь"].includes(light) || light === part) return part;
  if (light === "ночь") return part === "утро" ? "затемно" : "стемнело";
  if (light === "вечер") return "вечер";
  if (part === "ночь" && light === "утро") return "утро";
  return part === "вечер" || part === "ночь" ? "светло" : part;
}

export function randomSky({ seed = 0, at = 0, month = 0 } = {}) {
  const odds = SKY_ODDS[month === 12 || month === 1 || month === 2 ? "winter" : month >= 6 && month <= 8 ? "summer" : "between"];
  const total = odds.reduce((sum, [, weight]) => sum + weight, 0);
  let roll = hashOf(`${seed}:${Math.floor(Number(at) / SKY_SPAN_MS)}`) % total;
  for (const [sky, weight] of odds) { roll -= weight; if (roll < 0) return sky; }
  return odds[0][0];
}

