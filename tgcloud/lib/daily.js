/** Карта человека на день: одна и та же, сколько ни спрашивай. */
export function cardFor(userId, day) {
  let hash = 2166136261;
  for (const char of `${userId}:${day}`) { hash ^= char.codePointAt(0); hash = Math.imul(hash, 16777619) >>> 0; }
  return CARDS[hash % CARDS.length];
}

export const cardText = ([emoji, name, hint]) => `🃏 Карта дня — ${emoji} «${name}»\n${hint}\n\nЭто не предсказание, а подсказка на день.`;

const WHAT = "(вопрос(?:ы|а|ов)?\\s+дня|карт[ауы]?\\s+дня)";
const DAILY = "(?:по\\s+утрам|каждое\\s+утро|каждый\\s+день|ежедневно|каждый\\s+вечер|по\\s+вечерам)";
const SEND = "(?:(?:присылай|шли|задавай|давай|тяни|показывай|публикуй|пиши|включи|ставь|хочу)(?:те)?\\s+)?";
const TIME = "(?:\\s+в\\s+(\\d{1,2})(?:[:.](\\d{2}))?(?:\\s*(?:час(?:а|ов)?|ч))?(?:\\s+(утра|вечера|дня))?)?";
const ON = new RegExp(`^${SEND}${WHAT}\\s+${DAILY}${TIME}$`, "u");
const ON_FIRST = new RegExp(`^${SEND}${DAILY}${TIME}\\s+${WHAT}$`, "u");
const OFF = new RegExp(`^(?:не\\s+надо|не\\s+нужно|не\\s+присылай|не\\s+шли|не\\s+задавай|отключи|выключи|убери|отмени|хватит|стоп)(?:те)?\\s+(?:больше\\s+)?(?:присылать\\s+|слать\\s+|задавать\\s+)?${WHAT}(?:\\s+${DAILY})?$`, "u");
const CARD = /^(?:(?:вытяни|вытащи|достань|тяни|дай|покажи|какая)\s+(?:мне\s+)?)?(?:(?:моя|мою)\s+)?карт[ау]\s+дня(?:\s+(?:мне|сегодня|на\s+сегодня))?$|^(?:вытяни|вытащи|тяни|достань)\s+(?:мне\s+)?карту$|^(?:моя|какая\s+у\s+меня)\s+карта(?:\s+сегодня)?$/u;

/** «Карта дня», «вытяни карту». */
export const parseCard = (text) => CARD.test(fold(text).replace(/[?!.…]+$/u, ""));

/**
 * «Вопрос дня по утрам», «карта дня каждый день в 8», «не надо вопроса дня».
 * Возвращает `{ what: "question" | "card", on, hour, minute }` или null.
 */
export function parseDaily(text) {
  const value = fold(text).replace(/[?!.…]+$/u, "").replace(/\s+/gu, " ").trim();
  if (!value || value.length > 80) return null;
  const kind = (word) => (/^вопрос/u.test(word) ? "question" : "card");
  const off = value.match(OFF);
  if (off) return { what: kind(off[1]), on: false };
  const first = value.match(ON);
  const found = first ?? value.match(ON_FIRST);
  if (!found) return null;
  const [what, hourText, minuteText, part] = first ? [found[1], found[2], found[3], found[4]] : [found[4], found[1], found[2], found[3]];
  const evening = /вечер/u.test(value) && !hourText;
  let hour = hourText == null ? (evening ? 20 : 9) : Number(hourText);
  const minute = Number(minuteText) || 0;
  if ((part === "вечера" || part === "дня") && hour < 12) hour += 12;
  if (hour > 23 || minute > 59) return null;
  return { what: kind(what), on: true, hour, minute };
}

