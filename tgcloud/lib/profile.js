const SET = /^(?:оформи|обнови|поставь|настрой|заполни)\s+(?:себе\s+|свой\s+|мой\s+|твой\s+)?(?:профиль|описание(?:\s+(?:бота|профиля))?|страницу\s+бота)$/u;
const SHOW = /^(?:покажи|какой\s+у\s+тебя|какое\s+у\s+тебя)\s+(?:свой\s+|твой\s+|свое\s+)?(?:профиль|описание(?:\s+(?:бота|профиля))?)$/u;
/** «Оформи профиль» → `{ set: true }`, «покажи профиль» → `{ show: true }`, иначе null. */
export function profileWish(text) {
  const value = String(text ?? "").toLowerCase().replace(/ё/gu, "е").replace(/[«»"“”]/gu, "").replace(/\s+/gu, " ").trim().replace(/[.!?…]+$/u, "").trim();
  if (!value || value.length > 60) return null;
  return SET.test(value) ? { set: true } : SHOW.test(value) ? { show: true } : null;
}
