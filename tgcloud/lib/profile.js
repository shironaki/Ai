// «Мой профиль» и «покажи профиль» — карточка самого человека (намерение `profile`): её слова сюда не входят.
const OWN = "(?:себе\\s+|свой\\s+|твой\\s+|свое\\s+|твое\\s+)?";
const WHAT = "(?:профиль(?:\\s+бота)?|описание(?:\\s+(?:бота|профиля))?|страницу\\s+бота)";
const SET = new RegExp(`^(?:(?:оформи|обнови|поставь|настрой|заполни|установи)\\s+${OWN}${WHAT}|оформи\\s+себя)$`, "u");
// Сами слова лежат в коде: «поменяй описание» она выполнить не может — и говорит об этом, а не делает вид.
const CHANGE = new RegExp(`^(?:поменяй|измени|смени|перепиши|исправь|отредактируй)\\s+${OWN}${WHAT}$`, "u");
const SHOW = new RegExp(`^(?:(?:покажи|прочитай|открой)\\s+(?:(?:свой|твой)\\s+профиль|(?:свое|твое)\\s+описание|(?:профиль|описание)\\s+бота|описание\\s+профиля)|как(?:ой|ое)\\s+у\\s+тебя\\s+(?:профиль|описание)`
  + `|(?:твой|свой)\\s+профиль|твое\\s+описание|профиль\\s+бота|что\\s+(?:написано\\s+|стоит\\s+)?(?:у\\s+тебя\\s+)?в\\s+(?:твоем\\s+|своем\\s+)?(?:профиле|описании)`
  // «Профиль оформлен?», «ты оформила профиль?» — вопрос о том, стоит ли: она показывает и говорит, что в Telegram на деле.
  + `|(?:ты\\s+)?оформила\\s+(?:свой\\s+)?профиль|(?:твой\\s+)?профиль\\s+(?:оформлен|готов|стоит|поставлен|обновлен|на\\s+месте)|описание\\s+(?:стоит|поставлено|обновлено|готово|на\\s+месте)`
  + `|проверь\\s+(?:свой\\s+|твой\\s+)?профиль|что\\s+с\\s+(?:твоим\\s+)?профилем)$`, "u");
// Картинки (0.36.0): аватарка и картинка стартовой страницы. Ставит их человек — она говорит где, а не ищет картинку в сети.
const PICTURE = new RegExp(`^(?:(?:(?:поставь|смени|поменяй|обнови|установи|загрузи|покажи|пришли|скинь)\\s+)?(?:себе\\s+|свою\\s+|твою\\s+)?(?:аватарку|аватар|аву|(?:стартовую|приветственную)\\s+картинку|картинку\\s+(?:профиля|бота|стартовой\\s+страницы|приветствия)|фото\\s+профиля|обложку\\s+профиля)`
  + `|какая\\s+у\\s+тебя\\s+(?:аватарка|ава|картинка\\s+профиля)|где\\s+(?:картинка|аватарка)\\s+профиля|что\\s+с\\s+(?:картинкой\\s+профиля|аватаркой))$`, "u");
// «Покажи профиль» без «свой» — двусмысленно: карточку человека ведёт сестра. Её слова это, только когда
// речь уже шла о её профиле или сестра недоступна: решает сердце (`loose`). «Мой профиль» — всегда карточка.
const LOOSE = /^(?:(?:покажи|открой|посмотреть|глянь)\s+)?профиль$/u;
/**
 * «Оформи профиль» → `{ set: true }`, «покажи свой профиль» → `{ show: true }`, «поменяй описание» → `{ change: true }`,
 * «поставь аватарку» → `{ picture: true }`, иначе null. С `loose` ещё и «покажи профиль» → `{ show: true, loose: true }`.
 */
export function profileWish(text, { loose = false } = {}) {
  const value = String(text ?? "").toLowerCase().replace(/ё/gu, "е").replace(/[«»"“”]/gu, "").replace(/\s+/gu, " ").trim().replace(/[.!?…]+$/u, "").trim();
  if (!value || value.length > 60) return null;
  return SET.test(value) ? { set: true } : SHOW.test(value) ? { show: true } : CHANGE.test(value) ? { change: true } : PICTURE.test(value) ? { picture: true }
    : loose && LOOSE.test(value) ? { show: true, loose: true } : null;
}
