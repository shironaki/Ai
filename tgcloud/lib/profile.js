/**
 * Профиль бота (0.35.0): строка «О себе» и описание на стартовой странице — то, что человек
 * видит до первого слова. Слова — её голосом. Ставит она их сама по слову хозяина («оформи
 * профиль»); картинку стартовой страницы (640×360, `docs/profile/welcome.jpg`) Telegram даёт
 * поставить только человеку — в настройках бота.
 */
