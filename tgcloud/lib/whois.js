/**
 * После 2021 года номера перешли за пять миллиардов. Этих точек в открытой
 * таблице нет: они грубые, по порядку величины, и ответ об этом предупреждает.
 * Уточнять — по живым данным: дата известна, номер известен, строка сюда.
 */
const ROUGH = [
  [2147483647, utc(2021, 12)], [5000000000, utc(2021, 12, 15)], [5500000000, utc(2022, 7)], [6000000000, utc(2023, 3)],
  [6500000000, utc(2023, 10)], [7000000000, utc(2024, 4)], [7500000000, utc(2024, 10)], [8000000000, utc(2025, 4)],
];
export const ROUGH_FROM = 1974255900;
const ANCHORS = [...EXACT, ...ROUGH].sort((a, b) => a[0] - b[0]);

const MONTH_IN = ["январе", "феврале", "марте", "апреле", "мае", "июне", "июле", "августе", "сентябре", "октябре", "ноябре", "декабре"];

/**
 * Оценка даты регистрации по номеру.
 * Возвращает `{ at, rough, edge }`: `edge` — «before» (раньше таблицы) или
 * «after» (новее последней точки), иначе null.
 */
export function registeredAt(id, now = Date.now()) {
  const value = Number(id);
  if (!Number.isFinite(value) || value <= 0) return null;
  const first = ANCHORS[0], last = ANCHORS.at(-1);
  if (value <= first[0]) return { at: first[1], rough: false, edge: "before" };
  if (value >= last[0]) {
    // Дальше последней точки — тем же темпом, но не позже сегодняшнего дня.
    const prev = ANCHORS.at(-2);
    const at = last[1] + (value - last[0]) * ((last[1] - prev[1]) / (last[0] - prev[0]));
    return { at: Math.min(at, now), rough: true, edge: "after" };
  }
  let index = 1;
  while (ANCHORS[index][0] < value) index += 1;
  const [lowId, lowAt] = ANCHORS[index - 1], [highId, highAt] = ANCHORS[index];
  const at = lowAt + (value - lowId) * ((highAt - lowAt) / (highId - lowId));
  return { at: Math.min(at, now), rough: value > ROUGH_FROM, edge: null };
}

/** После «около» — родительный: «около 1 года», «около 5 лет». */
const years = (n) => `${n} ${n % 10 === 1 && n % 100 !== 11 ? "года" : "лет"}`;

/** «примерно в марте 2019 — аккаунту около 7 лет». */
export function registeredText(id, now = Date.now()) {
  const got = registeredAt(id, now);
  if (!got) return "";
  const date = new Date(got.at);
  const when = `${MONTH_IN[date.getUTCMonth()]} ${date.getUTCFullYear()}`;
  const age = Math.floor((now - got.at) / (365.25 * 86_400_000));
  const old = age >= 1 ? ` — аккаунту около ${years(age)}` : " — аккаунт совсем молодой";
  if (got.edge === "before") return `не позже ноября 2013 — один из первых аккаунтов`;
  return `примерно в ${when}${old}${got.rough ? " (оценка грубая: плюс-минус полгода)" : ""}`;
}

const ID_WORD = "(?:айди|айдишник|ид|id|номер\\s+аккаунта)";
const TG = "(?:\\s+(?:в|на)\\s+(?:телеграм[а-я]*|телеге|тг|telegram))";
// «Зарегистрировался» понятно и без уточнения; «пришёл» и «появился» — только «в телеграме».
const REG = `(?:(?:зарегистрировал(?:ся|ась|ись)?|зарегал(?:ся|ась)?|зареган[аы]?|регистрировал(?:ся|ась)|созда(?:л|ла)\\s+аккаунт)${TG}?|(?:появил(?:ся|ась)|пришел|пришла)${TG})`;
const SELF = new RegExp(
  `^(?:(?:скажи|покажи|напомни|какой|дай|узнай|назови)\\s+)*(?:(?:у\\s+меня|мой|мне|свой)\\s+)+${ID_WORD}$` +
  `|^(?:какой\\s+)?${ID_WORD}\\s+(?:у\\s+меня|мой)$` +
  `|^когда\\s+я\\s+${REG}$` +
  `|^(?:(?:скажи|покажи|какая)\\s+)?(?:дат[ауы]\\s+)?(?:моей\\s+)?регистраци[ияю](?:\\s+(?:моя|моего\\s+аккаунта|аккаунта))?$` +
  `|^(?:сколько\\s+лет|возраст)\\s+(?:моему\\s+|моего\\s+)?аккаунт[ау]$` +
  `|^(?:сколько\\s+(?:я\\s+)?(?:уже\\s+)?в\\s+(?:телеграм[а-я]*|телеге|тг))$`, "u");
const OTHER = new RegExp(
  `^(?:(?:скажи|покажи|какой|дай|узнай|назови)\\s+)*(?:(?:его|ее|их|этот|чей(?:\\s+это)?|у\\s+него|у\\s+нее)\\s+)*${ID_WORD}(?:\\s+(?:его|ее|у\\s+него|у\\s+нее|этого\\s+человека))?$` +
  `|^когда\\s+(?:он|она|они|этот\\s+человек)\\s+${REG}$` +
  `|^(?:дат[ауы]\\s+)?(?:его\\s+|ее\\s+)?регистраци[ияю](?:\\s+(?:его|ее))?$` +
  `|^(?:сколько\\s+лет|возраст)\\s+(?:его\\s+|ее\\s+|этому\\s+)?аккаунт[ау]$` +
  `|^(?:инфо|инфа|информация|кто\\s+это|пробей|пробить)$`, "u");
/** Только слово «айди»: без адресата это вопрос о себе. */
const BARE = new RegExp(`^(?:(?:скажи|покажи|какой|дай|узнай|назови)\\s+)*${ID_WORD}$`, "u");
const CHAT = new RegExp(`^(?:(?:скажи|покажи|какой|дай)\\s+)*${ID_WORD}\\s+(?:этого\\s+)?(?:чата|группы|канала|беседы)$|^(?:(?:скажи|покажи|какой|дай)\\s+)*(?:чата|группы|канала)\\s+${ID_WORD}$`, "u");

/**
 * Что спрашивают: `{ about: "self" | "other" | "chat" }` или null.
 * «other» имеет смысл только с адресатом — ответом на сообщение или
 * упоминанием; `loose` — без адресата это вопрос о себе («айди»).
 */
export function parseWhois(text) {
  const value = fold(text).replace(/[?!.…]+$/u, "").replace(/@[a-z0-9_]{3,32}/giu, " ").replace(/\s+/gu, " ").trim();
  if (!value) return null;
  if (CHAT.test(value)) return { about: "chat" };
  if (SELF.test(value)) return { about: "self" };
  if (OTHER.test(value)) return { about: "other", loose: BARE.test(value) };
  return null;
}
